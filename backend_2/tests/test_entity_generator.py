class StubLLMForGeneration:
    """Stub LLM client for testing entity generation."""

    def __init__(self, response: str) -> None:
        self._response = response

    async def chat(self, *args, **kwargs) -> str:
        return self._response


class StubPolicyForGeneration:
    """Stub model policy for testing."""

    def get_model(self, task):
        return "fake-model"


@pytest.mark.asyncio
async def test_entity_generator_extracts_properties():
    """Test that the entity generator can extract properties from text."""
    llm_response = """
    {
      "properties": [
        {
          "definition_id": 1,
          "value": "Tall, dark hair"
        }
      ],
      "relationships": [
        {
          "definition_id": 2,
          "target_alias": "Alice",
          "justification": "John is friends with Alice"
        }
      ],
      "autogenerated_summary": "John is a character with dark hair who is friends with Alice."
    }
    """

    generator = EntityGenerator(
        llm_client=StubLLMForGeneration(llm_response),
        model_policy=StubPolicyForGeneration(),
    )

    entity_def_map = {
        5: {
            "id": 5,
            "name": "Character",
            "description": "A person in the story",
            "properties": [
                {
                    "id": 1,
                    "name": "appearance",
                    "description": "Physical description",
                    "data_type": "text",
                    "cardinality": "one",
                }
            ],
            "relationships": [
                {
                    "id": 2,
                    "name": "friend_of",
                    "description": "Is friends with",
                    "destiny_entity_id": 5,
                    "destiny_entity_name": "Character",
                }
            ],
        }
    }

    proposals = [
        {
            "id": "proposal-1",
            "entity_definition_id": 5,
            "alias": "John",
            "chunks": ["John has dark hair and is tall. He is friends with Alice."],
        }
    ]

    entities = await generator.generate_new_entities(
        proposals=proposals,
        entity_definitions_map=entity_def_map,
        original_text="Story about John and Alice",
        author_type="agent",
        author_id="test-agent",
    )

    assert len(entities) == 1
    entity = entities[0]
    assert entity.alias == "John"
    assert entity.definition_id == 5
    assert len(entity.properties) == 1
    assert entity.properties[0].definition_id == 1
    assert entity.properties[0].value == "Tall, dark hair"
    assert "John is a character" in entity.autogenerated_text


