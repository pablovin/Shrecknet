from app.schemas.ontology_instance import OntologyInstanceRead
from app.services.atlas_folio_service import AtlasFolioService
from app.services.ontology_instance_service import FolioEditConflict, OntologyInstanceService

REVISION = "2026-10-01T00:00:00Z"


def page():
    return OntologyInstanceRead.model_validate({
        "instance_id": "page", "ontology_id": 7, "name": "Page",
        "created_at": REVISION, "updated_at": REVISION,
        "entities": [{"entity_instance_id": "one", "definition_id": 1, "alias": "one",
            "text": "Source", "text_linked": "Linked source", "autogenerated_text": "Generated",
            "created_date": REVISION, "last_updated_date": REVISION,
            "author_type": "human", "author_id": "4",
            "properties": [{"definition_id": 9, "value": ["unchanged"]}]}],
    })


@pytest.mark.parametrize("changes", [{}, {"name": "  "}, {"text": None}, {"properties": None}, {"author_id": "attacker"}])
def test_patch_rejects_invalid_or_noneditable_fields(changes):
    with pytest.raises(ValidationError):
        AtlasFolioPatch(expected_updated_at=REVISION, entity_instance_id="one", **changes)


@pytest.mark.asyncio
async def test_patch_preserves_unsupplied_fields_and_scopes_update_to_selected_entity():
    current = page()
    instances = SimpleNamespace(graph_session=None, sql_session=None,
        get_instance=AsyncMock(return_value=current), update_instance=AsyncMock(return_value=current))
    service = AtlasFolioService(instances)
    service.assert_page = AsyncMock()
    result = await service.patch(7, "page", AtlasFolioPatch(expected_updated_at=REVISION, entity_instance_id="one", name="Revised"))
    _, payload = instances.update_instance.call_args.args
    assert payload.name == "Revised"
    assert payload.entities[0].text == "Source"
    assert payload.entities[0].author_id == "4"
    assert payload.entities[0].properties[0].value == ["unchanged"]
    assert instances.update_instance.call_args.kwargs["edit_fields"] == set()
    assert result.folio_projection.relationships == "omitted"
    instances.get_instance.assert_awaited_once_with("page", include_scenes=False, include_relationships=False)


@pytest.mark.asyncio
async def test_patch_rejects_stale_revision_or_foreign_entity_without_writing():
    current = page()
    instances = SimpleNamespace(graph_session=None, sql_session=None, get_instance=AsyncMock(return_value=current), update_instance=AsyncMock())
    service = AtlasFolioService(instances)
    service.assert_page = AsyncMock()
    with pytest.raises(FolioEditConflict):
        await service.patch(7, "page", AtlasFolioPatch(expected_updated_at="2026-09-01T00:00:00Z", entity_instance_id="one", text="Changed"))
    with pytest.raises(ValueError, match="does not belong"):
        await service.patch(7, "page", AtlasFolioPatch(expected_updated_at=REVISION, entity_instance_id="other", text="Changed"))
    instances.update_instance.assert_not_awaited()


@pytest.mark.asyncio
@pytest.mark.parametrize("role", [UserRole.PLAYER, UserRole.WORLD_BUILDER])
async def test_patch_denies_nonadmins_before_mutation(role):
    service = SimpleNamespace(assert_ontology_graph_read_access=AsyncMock())
    app = FastAPI()
    app.include_router(router)
    app.dependency_overrides[get_current_user] = lambda: SimpleNamespace(id=4, role=role)
    app.dependency_overrides[get_ontology_instance_service] = lambda: service
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://test") as client:
        response = await client.patch("/ontologies/7/pages/page/folio", json={"expected_updated_at": REVISION, "entity_instance_id": "one", "name": "Changed"})
    assert response.status_code == 403


@pytest.mark.asyncio
async def test_revision_is_checked_again_under_transaction_lock():
    tx = SimpleNamespace(run=AsyncMock(return_value=SimpleNamespace(single=AsyncMock(return_value={"revision": "2026-10-02T00:00:00Z"}))), rollback=AsyncMock(), close=AsyncMock())
    graph = SimpleNamespace(begin_transaction=AsyncMock(return_value=tx), run=AsyncMock())
    service = OntologyInstanceService.__new__(OntologyInstanceService)
    service.graph_session = graph
    service.get_instance = AsyncMock(return_value=page())
    service._load_entity_definitions = AsyncMock(return_value={1: {"properties": {}, "relationships": {}}})
    from app.schemas.ontology_instance import OntologyInstanceEntityCreate, OntologyInstanceUpdate
    entity = OntologyInstanceEntityCreate.model_validate(page().entities[0].model_dump())
    with pytest.raises(FolioEditConflict):
        await service.update_instance("page", OntologyInstanceUpdate(name="Changed", entities=[entity]), expected_updated_at=datetime(2026, 10, 1, tzinfo=timezone.utc), edit_fields=set())
    tx.rollback.assert_awaited_once()
    graph.run.assert_not_awaited()
    assert tx.run.await_count == 1


@pytest.mark.asyncio
async def test_partial_update_writes_only_supplied_fields_and_preserves_sibling_facets(monkeypatch):
    import app.services.ontology_instance_service as module
    from app.tasks.neo4j_embedding import embed_nodes
    from app.schemas.ontology_instance import OntologyInstanceEntityCreate, OntologyInstanceUpdate

    current = page()
    sibling = current.entities[0].model_copy(update={"entity_instance_id": "two", "alias": "two"})
    current.entities.append(sibling)
    results = [
        SimpleNamespace(single=AsyncMock(return_value={"revision": REVISION})),
        SimpleNamespace(),
        SimpleNamespace(data=AsyncMock(return_value=[
            {"entity_instance_id": "one", "alias": "one", "definition_id": 1},
            {"entity_instance_id": "two", "alias": "two", "definition_id": 1},
        ])),
        SimpleNamespace(),
    ]
    tx = SimpleNamespace(run=AsyncMock(side_effect=results), commit=AsyncMock(), rollback=AsyncMock(), close=AsyncMock())
    graph = SimpleNamespace(begin_transaction=AsyncMock(return_value=tx), run=AsyncMock())
    service = OntologyInstanceService.__new__(OntologyInstanceService)
    service.graph_session = graph
    service.get_instance = AsyncMock(return_value=current)
    service._load_entity_definitions = AsyncMock(return_value={1: {"properties": {}, "relationships": {}}})
    monkeypatch.setattr(module, "_enqueue_link_instance", lambda _: None)
    monkeypatch.setattr(embed_nodes, "delay", lambda *_: None)
    entity = OntologyInstanceEntityCreate.model_validate(current.entities[0].model_dump())
    entity.text = "Changed text"
    await service.update_instance("page", OntologyInstanceUpdate(entities=[entity]), expected_updated_at=current.updated_at, edit_fields={"text"})
    writes = tx.run.call_args_list[-1].kwargs
    assert writes["entity_instance_id"] == "one"
    assert writes["changes"]["text"] == "Changed text"
    assert writes["changes"]["text_linked"] == "Changed text"
    assert set(writes["changes"]) == {"text", "text_linked", "updated_at", "last_updated_date"}
    assert tx.run.await_count == 4  # No relationship fetch/rewrite.
    tx.commit.assert_awaited_once()
    tx.rollback.assert_not_awaited()
    graph.run.assert_not_awaited()
