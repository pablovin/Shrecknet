"""Public, bounded Atlas discovery response models."""
from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, Field


class AtlasFolioProjection(BaseModel):
    scenes: Literal["omitted"]
    relationships: Literal["omitted"]


class AtlasFolioEntity(BaseModel):
    entity_instance_id: str
    definition_id: int
    alias: str | None = None
    text: str
    text_linked: str | None = None
    node_avatar_url: str | None = None
    autogenerated_text: str | None = None
    autogenerated_text_linked: str | None = None
    created_date: datetime
    last_updated_date: datetime
    author_type: Literal["human", "agent"]
    author_id: str
    has_agent: bool = False
    agent_id: str | None = None
    agent_name: str | None = None
    properties: list[dict[str, Any]] = Field(default_factory=list)
    relationships: list[dict[str, Any]] = Field(default_factory=list)


class AtlasFolioDetail(BaseModel):
    instance_id: str
    ontology_id: int
    name: str
    created_at: datetime
    updated_at: datetime
    entities: list[AtlasFolioEntity]
    scenes: list[dict[str, Any]] = Field(default_factory=list)
    folio_projection: AtlasFolioProjection


class AtlasAuthor(BaseModel):
    id: str
    type: Literal["human", "agent"]
    display_name: str
    avatar_url: str | None = None


class AtlasRelationshipTarget(BaseModel):
    entity_id: str
    page_id: str
    definition_id: int
    title: str
    avatar_url: str | None = None


class AtlasRelationshipRow(BaseModel):
    id: str
    definition_id: int
    direction: Literal["incoming", "outgoing"]
    focus_entity_id: str
    target: AtlasRelationshipTarget


class AtlasRelationshipGroup(BaseModel):
    key: str
    definition_id: int
    direction: Literal["incoming", "outgoing"]
    label: str | None = None
    total: int = Field(ge=0)


class AtlasRelationshipPage(BaseModel):
    results: list[AtlasRelationshipRow]
    groups: list[AtlasRelationshipGroup]
    total: int = Field(ge=0)
    skip: int = Field(ge=0)
    limit: int = Field(ge=1, le=100)


class AtlasSourceReference(BaseModel):
    id: str
    display_name: str
    avatar_url: str | None = None


class AtlasSourceCard(AtlasSourceReference):
    scene_count: int
    latest_activity: str | None = None


class AtlasSourcePage(BaseModel):
    results: list[AtlasSourceCard]
    skip: int
    limit: int
    has_more: bool


class AtlasSourceAnchor(BaseModel):
    entity_instance_id: str


class AtlasSceneOrder(BaseModel):
    followed_by_scene_id: str | None = None
    preceded_by_scene_id: str | None = None


class AtlasScene(BaseModel):
    id: str
    name: str
    description: str | None = None
    derived_from: AtlasSourceAnchor | None = None
    local_order: AtlasSceneOrder = Field(default_factory=AtlasSceneOrder)
    milestone_count: int


class AtlasOwningInstance(BaseModel):
    instance_id: str
    name: str


class AtlasSceneRow(BaseModel):
    scene: AtlasScene
    instance: AtlasOwningInstance
    source_page: AtlasSourceReference | None = None
    perspective_count: int


class AtlasScenePage(BaseModel):
    related_only: bool = False
    results: list[AtlasSceneRow]
    skip: int
    limit: int
    total: int


class AtlasElderCard(BaseModel):
    id: str
    name: str
    avatar_url: str | None = None
    description: str | None = None


class AtlasWebNode(BaseModel):
    id: str
    kind: Literal["entity", "source", "scene", "milestone"]
    name: str
    page_id: str


class AtlasWebEdge(BaseModel):
    source: str
    target: str
    label: str


class AtlasWorldWeb(BaseModel):
    ontology_id: int
    nodes: list[AtlasWebNode]
    edges: list[AtlasWebEdge]
    truncated: bool
