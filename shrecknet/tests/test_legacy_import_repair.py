class _FakeResult:
    def __init__(self, *, rows=None, single_row=None):
        self._rows = rows or []
        self._single_row = single_row

    async def data(self):
        return self._rows

    async def single(self):
        return self._single_row


class _FakeTx:
    def __init__(self) -> None:
        self.runs: list[tuple[str, dict]] = []
        self.committed = False
        self.rolled_back = False
        self.closed = False

    async def run(self, query, **params):
        self.runs.append((query, params))
        return _FakeResult()

    async def commit(self):
        self.committed = True

    async def rollback(self):
        self.rolled_back = True

    async def close(self):
        self.closed = True


class _FakeGraphSession:
    def __init__(self, rows, entity_rows=None):
        self.rows = rows
        self.entity_rows = entity_rows or []
        self.txs: list[_FakeTx] = []

    async def run(self, query, params=None, **kwargs):
        if "RETURN event.event_id AS event_id" in query:
            return _FakeResult(rows=self.rows)
        if "collect(DISTINCT entity.entity_instance_id) AS entity_ids" in query:
            return _FakeResult(rows=self.entity_rows)
        return _FakeResult()

    async def begin_transaction(self):
        tx = _FakeTx()
        self.txs.append(tx)
        return tx


class _RecordingGraphSession:
    def __init__(self, rows):
        self.rows = rows
        self.runs: list[tuple[str, dict]] = []

    async def run(self, query, params=None, **kwargs):
        call_params = params or kwargs or {}
        self.runs.append((query, call_params))
        if "RETURN event.event_id AS event_id" in query:
            return _FakeResult(rows=self.rows)
        if "RETURN count(rel) AS count" in query:
            return _FakeResult(single_row={"count": 0})
        return _FakeResult()


