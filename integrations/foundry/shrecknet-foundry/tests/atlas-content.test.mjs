test("relationship cards use page names and type definitions within the source ontology", async () => {
  const requests = [];
  const app = Object.create(ShrecknetShell.prototype);
  app.relationshipCardsByInstance = new Map();
  app.atlasDefinitionsByOntology = new Map();
  app.client = {
    listEntityTypes: async (id, options) => { requests.push([id, options]); return [{ id: 2, name: "Character" }]; },
    listEntityRelationships: async () => [{ id: 4, name: "Features" }],
    resolveEntities: async (id, ids) => {
      assert.equal(id, 12);
      assert.deepEqual(ids, ["a", "b", "missing"]);
      return { results: [{ entity_instance_id: "a", instance_id: "page-a", entity_definition_id: 2, instance_name: "Raist Profile", entity_alias: "Alias", avatar_url: null }] };
    },
    resolveUrl: (url) => url,
  };
  const instance = { instance_id: "source", ontology_id: 12, entities };
  const resolved = await app._resolveRelationshipCards(instance);
  assert.equal(resolved.get("a").name, "Raist Profile");
  assert.equal(resolved.get("a").typeName, "Character");
  assert.deepEqual(requests, [[12, { displayedOnly: false }]]);
  assert.equal(await app._resolveRelationshipCards(instance), resolved);
});

