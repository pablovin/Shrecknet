def _legacy(path: Path) -> None:
    with sqlite3.connect(path) as conn:
        conn.executescript("""
            CREATE TABLE ontology_entities(id INTEGER PRIMARY KEY, name TEXT);
            CREATE TABLE entity_relationships(id INTEGER PRIMARY KEY, entity_id INTEGER,
                destiny_entity_id INTEGER, name TEXT);
            CREATE TABLE entity_properties(id INTEGER PRIMARY KEY, entity_id INTEGER, name TEXT);
            INSERT INTO ontology_entities VALUES(1, 'Adventures'), (2, 'Story Arcs'),
                (3, 'Stories'), (4, 'Timeline');
            INSERT INTO entity_relationships VALUES(7, 1, 2, 'has story arc'),
                                                    (8, 2, 3, 'contains stories'),
                                                    (9, 1, 4, 'has timeline');
        """)


def _node(id: str, definition_id: int, title: str, instance_id: str,
          text: str = "", image: str | None = None,
          autogenerated_text: str = "") -> dict:
    return dict(id=id, definition_id=definition_id, title=title, instance_id=instance_id,
                text=text, autogenerated_text=autogenerated_text, image=image,
                properties="{}", created_date="")


def _world(extra: bool = False) -> dict:
    nodes = {
        "adventure": _node("adventure", 1, "the_wolf_of_midnight", "page-a", "Adventure introduction"),
        "arc": _node("arc", 2, "arc_01_trouble", "page-arc", "The first arc"),
        "story-1": _node("story-1", 3, "story_01_first_steps", "page-s1", "First story", "/media/scene/story.png"),
        "story-2": _node("story-2", 3, "story_02_the_return", "page-s2", "Second story",
                         autogenerated_text="Generated story details"),
    }
    edges = [("adventure", "arc", 7), ("arc", "story-1", 8), ("arc", "story-2", 8)]
    anchors = [("page-s1", "story-1"), ("page-s2", "story-2")]
    if extra:
        nodes["story-3"] = _node("story-3", 3, "story_03_one_more_time", "page-s3", "Third story")
        edges.append(("arc", "story-3", 8))
        # This story has no Scene of its own. A scene under the same adventure
        # should still select it through the complete ontology relationship graph.
    return {"ontology_id": 42, "scene_anchors": anchors, "nodes": nodes, "edges": edges}


def _init(tmp_path, monkeypatch):
    legacy = tmp_path / "legacy.db"
    _legacy(legacy)
    legacy_media = tmp_path / "legacy_media"
    (legacy_media / "scene").mkdir(parents=True)
    (legacy_media / "scene" / "story.png").write_bytes(bytes.fromhex("89504e470d0a1a0a") + b"sample")
    settings = SimpleNamespace(
        legacy_ontology_database_path=legacy,
        legacy_media_root=legacy_media,
        media_root=tmp_path / "media",
    )
    monkeypatch.setattr(assets, "get_settings", lambda: settings)
    monkeypatch.setattr(collections, "get_settings", lambda: settings)
    monkeypatch.setattr(workspace, "get_settings", lambda: settings)
    engine = create_engine("sqlite+pysqlite:///" + str(tmp_path / "sources.db"))
    Base.metadata.create_all(engine)
    return settings, engine, sessionmaker(bind=engine)


def test_graph_import_builds_one_world_hierarchy_and_attaches_documents(tmp_path, monkeypatch):
    settings, engine, factory = _init(tmp_path, monkeypatch)
    monkeypatch.setattr(importer, "_graph_worlds", lambda _: [_world()])

    first = importer.import_graph_sources(factory, settings)
    assert first["hierarchies"] == 1
    assert first["entries_added"] == 4
    assert first["documents_created"] == 4
    assert first["errors"] == 0

    with Session(engine) as db:
        templates = db.scalars(select(SourceHierarchy).where(SourceHierarchy.source_type == "narrative")).all()
        assert len(templates) == 1
        assert templates[0].section_types == ["Adventures", "Story Arcs", "Stories"]
        assert templates[0].name == "Adventures → Story Arcs → Stories"
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 42))
        assert collection is not None
        assert collection.hierarchy_template_id == templates[0].id
        entries = {entry.title: entry for entry in
                   (CollectionEntry.model_validate(row) for row in collection.nodes)}
        assert len(entries) == 4
        root = entries["The Wolf Of Midnight"]
        arc = entries["Arc 01 Trouble"]
        story = entries["Story 01 First Steps"]
        assert (root.level, root.parent_id) == (0, None)
        assert (arc.level, arc.parent_id) == (1, root.id)
        assert (story.level, story.parent_id) == (2, arc.id)
        assert len(story.source_ids) == 1
        assert len(db.scalars(select(GraphSourceImport)).all()) == 4
        assert len(db.scalars(select(SourceAsset)).all()) == 4
        item = db.get(ShreckWorldLibraryItem, story.source_ids[0])
        assert item is not None and item.source_type == "narrative"
        organization = workspace.get_organization(db, item)
        content_section = next(section for section in organization.nodes if section.parent_id is not None)
        assert content_section.metadata.markdown_asset_id
        md_asset = db.get(SourceAsset, content_section.metadata.markdown_asset_id)
        assert md_asset and "First story" in Path(md_asset.storage_path).read_text()
        generated = next(entry for entry in entries.values() if entry.title == "Story 02 The Return")
        generated_item = db.get(ShreckWorldLibraryItem, generated.source_ids[0])
        generated_org = workspace.get_organization(db, generated_item)
        generated_section = next(section for section in generated_org.nodes if section.parent_id is not None)
        generated_asset = db.get(SourceAsset, generated_section.metadata.markdown_asset_id)
        generated_markdown = Path(generated_asset.storage_path).read_text()
        assert "Second story" in generated_markdown
        assert "Generated text" in generated_markdown
        assert "Generated story details" in generated_markdown
        assert assets.read_asset(db, item.id, md_asset.id).id == md_asset.id
        image_path = collections._image_root(collection, story.id) / story.image_key
        assert story.image_key and image_path.is_file()

        original_collection_revision = collection.revision
        source_ids = set(db.scalars(select(ShreckWorldLibraryItem.id)).all())

    second = importer.import_graph_sources(factory, settings)
    assert second["entries_added"] == 0
    assert second["documents_created"] == 0
    with Session(engine) as db:
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 42))
        assert collection.revision == original_collection_revision
        assert set(db.scalars(select(ShreckWorldLibraryItem.id)).all()) == source_ids

    monkeypatch.setattr(importer, "_graph_worlds", lambda _: [_world(extra=True)])
    third = importer.import_graph_sources(factory, settings)
    assert third["entries_added"] == 1
    assert third["documents_created"] == 1
    with Session(engine) as db:
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 42))
        assert len(collection.nodes) == 5
        assert collection.revision == original_collection_revision + 1
        assert len(db.scalars(select(GraphSourceImport)).all()) == 5
    engine.dispose()


def test_story_documents_attach_without_overwriting_edits(tmp_path, monkeypatch):
    settings, engine, factory = _init(tmp_path, monkeypatch)
    monkeypatch.setattr(importer, "_graph_worlds", lambda _: [_world()])
    importer.import_graph_sources(factory, settings)
    with Session(engine) as db:
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 42))
        story = next(entry for entry in (CollectionEntry.model_validate(row) for row in collection.nodes)
                     if entry.title == "Story 01 First Steps")
        item = db.get(ShreckWorldLibraryItem, story.source_ids[0])
        organization = workspace.get_organization(db, item)
        changed = [type(section).model_validate(section.model_dump()) for section in organization.nodes]
        section = next(node for node in changed if node.parent_id is not None)
        asset = db.get(SourceAsset, section.metadata.markdown_asset_id)
        old_path = Path(asset.storage_path)
        section.content_reference.paragraphs[0].text = "My revised story text"
        section.metadata.markdown_asset_id = None
        workspace.save_organization(db, item, workspace.OrganizationInput(
            expected_revision=item.source_revision, nodes=changed,
        ))
        db.refresh(asset)
        assert "My revised story text" in Path(asset.storage_path).read_text(encoding="utf-8")
        assert old_path.exists() and "First story" in old_path.read_text(encoding="utf-8")

    importer.import_graph_sources(factory, settings)
    with Session(engine) as db:
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 42))
        story = next(entry for entry in (CollectionEntry.model_validate(row) for row in collection.nodes)
                     if entry.title == "Story 01 First Steps")
        item = db.get(ShreckWorldLibraryItem, story.source_ids[0])
        section = next(node for node in workspace.get_organization(db, item).nodes if node.parent_id is not None)
        assert section.content_reference.paragraphs[0].text == "My revised story text"
    engine.dispose()


def test_timelines_are_only_imported_when_nested_under_adventures(tmp_path, monkeypatch):
    assert importer._rank("Stories") == 2
    assert importer._rank("Story Arcs") == 1
    assert importer._rank("Adventures") == 0
    assert importer._rank("Timeline") == 2

    settings, engine, factory = _init(tmp_path, monkeypatch)
    world = {
        "ontology_id": 84,
        "scene_anchors": [("page-t1", "timeline-1")],
        "nodes": {
            "adventure": _node("adventure", 1, "The Tournament", "page-a", "Adventure text"),
            "timeline-1": _node("timeline-1", 4, "410 AD", "page-t1", "First period"),
            "timeline-2": _node("timeline-2", 4, "511 AD", "page-t2", "Second period"),
        },
        "edges": [("adventure", "timeline-1", 9), ("adventure", "timeline-2", 9)],
    }
    monkeypatch.setattr(importer, "_graph_worlds", lambda _: [world])
    summary = importer.import_graph_sources(factory, settings)
    assert summary["hierarchies"] == 1
    assert summary["entries_added"] == 3
    assert summary["errors"] == 0
    with Session(engine) as db:
        collection = db.scalar(select(SourceCollection).where(SourceCollection.ontology_id == 84))
        template = db.scalar(select(SourceHierarchy).where(SourceHierarchy.id == collection.hierarchy_template_id))
        entries = [CollectionEntry.model_validate(row) for row in collection.nodes]
        assert template.section_types == ["Adventures", "Timeline"]
        assert sorted(entry.level for entry in entries) == [0, 1, 1]
    engine.dispose()


