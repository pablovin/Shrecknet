# A terminal narrative node can be a Story, Session, Timeline, etc., but it
# must belong to an Adventure path. This prevents standalone Timeline imports.
NARRATIVE_TYPES = (
    (re.compile(r"\b(?:adventures?|campaigns?|sagas?|chronicles?|books?|novels?)\b", re.I), 0),
    (re.compile(r"\b(?:story[\s_-]*arcs?|arcs?|storylines?|seasons?|years?|volumes?|parts?|acts?)\b", re.I), 1),
    (re.compile(r"\b(?:stories|story|sessions?|timelines?|chapters?|episodes?|entries|entry)\b", re.I), 2),
)
MIN_NARRATIVE_LEVELS = 2
MAX_TREE_NODES = 2000
MAX_TREE_BYTES = 2_000_000


def _id(*parts: object) -> str:
    return str(uuid5(NAMESPACE_URL, "shreckworld-graph-import:" + ":".join(map(str, parts))))


def _rank(type_name: str) -> int | None:
    for expression, rank in NARRATIVE_TYPES:
        if expression.search(type_name):
            return rank
    return None


def _display_title(node: dict) -> str:
    raw = str(node.get("title") or node.get("alias") or node.get("id") or "").strip()
    return re.sub(r"\s+", " ", re.sub(r"[_-]+", " ", raw)).title()[:255] or "Untitled"


def _source_text(node: dict) -> tuple[list[dict], str]:
    human = (node.get("text") or "").strip()
    generated = (node.get("autogenerated_text") or "").strip()
    paragraphs: list[dict] = []
    if human:
        body = human if not generated or human == generated else "## Authored text\n\n" + human
        paragraphs.append({"id": _id(node["id"], "authored"), "text": body})
    if generated and generated != human:
        body = generated if not human else "## Generated text\n\n" + generated
        paragraphs.append({"id": _id(node["id"], "generated"), "text": body})
    digest = sha256((human + "\0" + generated).encode("utf-8")).hexdigest()
    return paragraphs, digest


@dataclass(frozen=True)
class LegacyType:
    id: int
    name: str


def _legacy_definitions(path: Path) -> tuple[dict[int, LegacyType], dict[int, dict], dict[int, dict]]:
    if not path.is_file():
        raise FileNotFoundError("Legacy ontology database is not mounted")
    conn = sqlite3.connect(f"file:{path.resolve().as_posix()}?mode=ro", uri=True)
    try:
        conn.row_factory = sqlite3.Row
        types = {int(x["id"]): LegacyType(int(x["id"]), str(x["name"]))
                 for x in conn.execute("SELECT id, name FROM ontology_entities")}
        relationships = {int(x["id"]): dict(x) for x in conn.execute(
            "SELECT id, entity_id, destiny_entity_id, name FROM entity_relationships")}
        props = {int(x["id"]): dict(x) for x in conn.execute(
            "SELECT id, entity_id, name FROM entity_properties")}
        return types, relationships, props
    finally:
        conn.close()


def _graph_worlds(settings) -> list[dict]:
    """Read every Neo4j ontology and its Scene anchors, entities and edges."""
    driver = GraphDatabase.driver(
        settings.graph_neo4j_uri,
        auth=(settings.graph_neo4j_user, settings.graph_neo4j_password),
        connection_timeout=5,
    )
    try:
        with driver.session(database=settings.graph_neo4j_database) as graph:
            ontology_rows = graph.run("""
                MATCH (entity:EntityInstance)
                WHERE toInteger(entity.ontology_id) IS NOT NULL
                RETURN DISTINCT toInteger(entity.ontology_id) AS ontology_id
                ORDER BY ontology_id
            """).data()
            ontology_ids = [int(row["ontology_id"]) for row in ontology_rows
                            if row["ontology_id"] is not None]
            anchors = graph.run("""
                MATCH (page:OntologyInstance)-[:HAS_SCENE]->(scene:Scene)
                      -[:DERIVED_FROM]->(leaf:EntityInstance)
                WHERE toString(scene.instance_id) = toString(page.instance_id)
                  AND toInteger(leaf.ontology_id) = toInteger(page.ontology_id)
                RETURN DISTINCT toInteger(page.ontology_id) AS ontology_id,
                       page.instance_id AS instance_id,
                       leaf.entity_instance_id AS entity_id
                ORDER BY ontology_id, instance_id, entity_id
            """).data()
            anchor_groups: dict[int, list[tuple[str, str]]] = defaultdict(list)
            for row in anchors:
                if row["ontology_id"] is not None and row["entity_id"]:
                    anchor_groups[int(row["ontology_id"])].append(
                        (str(row["instance_id"]), str(row["entity_id"]))
                    )

            worlds = []
            for ontology_id in ontology_ids:
                scene_anchors = anchor_groups.get(ontology_id, [])
                nodes: dict[str, dict] = {}
                for row in graph.run("""
                    MATCH (entity:EntityInstance)
                    WHERE toInteger(entity.ontology_id) = $ontology_id
                    RETURN entity
                """, ontology_id=ontology_id):
                    obj = dict(row["entity"])
                    entity_id = str(obj.get("entity_instance_id") or "")
                    if not entity_id:
                        continue
                    nodes[entity_id] = {
                        "id": entity_id,
                        "instance_id": str(obj.get("instance_id") or ""),
                        "definition_id": int(obj.get("entity_definition_id") or 0),
                        "title": str(obj.get("alias") or obj.get("normalized_name") or entity_id),
                        "text": obj.get("text") or "",
                        "autogenerated_text": obj.get("autogenerated_text") or "",
                        "image": obj.get("node_avatar_url"),
                        "properties": obj.get("properties") or "{}",
                        "created_date": str(obj.get("created_date") or ""),
                    }
                edges = []
                for row in graph.run("""
                    MATCH (a:EntityInstance)-[r:RELATES_TO]->(b:EntityInstance)
                    WHERE toInteger(a.ontology_id) = $ontology_id
                      AND toInteger(b.ontology_id) = $ontology_id
                    RETURN a.entity_instance_id AS a, b.entity_instance_id AS b,
                           r.relationship_definition_id AS definition_id
                """, ontology_id=ontology_id):
                    if row["a"] and row["b"] and row["definition_id"] is not None:
                        edges.append((str(row["a"]), str(row["b"]), int(row["definition_id"])))
                worlds.append({
                    "ontology_id": ontology_id,
                    "scene_anchors": scene_anchors,
                    "nodes": nodes,
                    "edges": edges,
                })
            return worlds
    finally:
        driver.close()


def _ancestry(leaf_id: str, nodes: dict, edges: list, types: dict,
              relationship_defs: dict) -> list[str]:
    """Follow verified narrative relationships to the nearest higher levels."""
    neighbours: dict[str, set[str]] = defaultdict(set)
    for source_id, target_id, definition_id in edges:
        definition = relationship_defs.get(definition_id)
        if definition is None or source_id not in nodes or target_id not in nodes:
            continue
        source, target = nodes[source_id], nodes[target_id]
        endpoint_types = {source["definition_id"], target["definition_id"]}
        expected_types = {
            int(definition["entity_id"]),
            int(definition["destiny_entity_id"] or -1),
        }
        if endpoint_types != expected_types:
            continue
        neighbours[source_id].add(target_id)
        neighbours[target_id].add(source_id)

    result = [leaf_id]
    visited = {leaf_id}
    current = leaf_id
    for _ in range(16):
        node_type = types.get(nodes[current]["definition_id"])
        current_rank = _rank(node_type.name) if node_type else None
        if current_rank is None:
            current_rank = 3
        candidates = []
        for neighbour in neighbours[current]:
            if neighbour in visited:
                continue
            target_type = types.get(nodes[neighbour]["definition_id"])
            ancestor_rank = _rank(target_type.name) if target_type else None
            if ancestor_rank is not None and ancestor_rank < current_rank:
                candidates.append((ancestor_rank, neighbour))
        if not candidates:
            break
        best_rank = max(rank for rank, _ in candidates)
        best = sorted(identifier for rank, identifier in candidates if rank == best_rank)
        if len(best) != 1:
            raise ValueError("ambiguous narrative parent")
        current = best[0]
        result.append(current)
        visited.add(current)
    else:
        raise ValueError("narrative ancestry exceeds 16 levels")
    return list(reversed(result))


def _valid_path(path: list[str], nodes: dict, types: dict) -> bool:
    ranks = []
    for identifier in path:
        node_type = types.get(nodes[identifier]["definition_id"])
        ranks.append(_rank(node_type.name) if node_type else None)
    return (
        len(ranks) >= MIN_NARRATIVE_LEVELS
        and ranks[0] == 0
        and ranks[-1] == 2
        and ranks == sorted(set(ranks))
    )


def _narrative_paths(world: dict, types: dict, relationship_defs: dict) -> list[list[str]]:
    nodes, edges = world["nodes"], world["edges"]
    anchored_ids = {entity_id for _, entity_id in world["scene_anchors"]}
    roots: set[str] = set()
    for leaf_id in anchored_ids:
        node = nodes.get(leaf_id)
        node_type = types.get(node["definition_id"]) if node else None
        if node_type is None or _rank(node_type.name) != 2:
            continue
        try:
            path = _ancestry(leaf_id, nodes, edges, types, relationship_defs)
            if _valid_path(path, nodes, types):
                roots.add(path[0])
        except ValueError:
            logger.warning("Skipping ambiguous scene-backed narrative leaf %s", leaf_id)

    # Once a scene anchors a narrative root, include every graph Story below
    # that root, not just leaves that happen to have a Scene of their own.
    unique: dict[tuple[str, ...], list[str]] = {}
    for leaf_id, node in nodes.items():
        node_type = types.get(node["definition_id"])
        if node_type is None or _rank(node_type.name) != 2:
            continue
        try:
            path = _ancestry(leaf_id, nodes, edges, types, relationship_defs)
            if _valid_path(path, nodes, types) and path[0] in roots:
                unique[tuple(path)] = path
        except ValueError:
            logger.warning("Skipping ambiguous narrative leaf %s", leaf_id)
    return list(unique.values())


def _properties(node: dict, prop_defs: dict) -> dict[str, object]:
    try:
        raw = json.loads(node["properties"]) if isinstance(node["properties"], str) else node["properties"]
        return {str(prop_defs[int(key)]["name"]).lower(): value for key, value in raw.items()
                if int(key) in prop_defs} if isinstance(raw, dict) else {}
    except (ValueError, TypeError):
        return {}


def _node_sort(node: dict, prop_defs: dict) -> tuple:
    props = _properties(node, prop_defs)
    for key in ("order", "sequence", "number", "position", "session_number"):
        value = props.get(key)
        if isinstance(value, (int, float)) or (isinstance(value, str) and value.isdigit()):
            return (0, float(value), _display_title(node).lower(), node["id"])
    return (1, str(node.get("created_date") or ""), _display_title(node).lower(), node["id"])


def _legacy_image(image_url: object, media_root: Path) -> tuple[bytes, str, str] | None:
    if not isinstance(image_url, str) or not image_url.strip():
        return None
    path = urlsplit(image_url.strip()).path
    if not path.startswith("/media/"):
        return None
    suffix = unquote(path[len("/media/"):])
    if not suffix or "\0" in suffix:
        return None
    root = media_root.resolve()
    file = (root / suffix).resolve()
    if root not in file.parents or not file.is_file() or file.stat().st_size > 5 * 1024 * 1024:
        return None
    data = file.read_bytes()
    if data.startswith(bytes.fromhex("89504e470d0a1a0a")):
        return data, "png", "image/png"
    if data.startswith(bytes.fromhex("ffd8ff")) and data.endswith(bytes.fromhex("ffd9")):
        return data, "jpg", "image/jpeg"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return data, "webp", "image/webp"
    return None


def _template_for_signature(db: Session, signature: tuple[str, ...]) -> SourceHierarchy | None:
    template_id = _id("template", "/".join(signature))
    template = db.scalar(select(SourceHierarchy).where(
        SourceHierarchy.id == template_id,
    ).order_by(SourceHierarchy.version.desc()).limit(1))
    if template is None:
        template = SourceHierarchy(
            id=template_id, version=1,
            name=" → ".join(signature),
            description="Narrative hierarchy imported from ontology entity types",
            section_types=list(signature), source_type="narrative", archived=False,
        )
        db.add(template)
        db.flush()
    if template.source_type != "narrative" or template.section_types != list(signature):
        raise ValueError("Generated narrative hierarchy template conflicts with existing data")
    if template.archived:
        return None
    return template


def _collection_for(db: Session, ontology_id: int, template: SourceHierarchy) -> tuple[SourceCollection, bool]:
    collection = db.scalar(select(SourceCollection).where(
        SourceCollection.ontology_id == ontology_id,
        SourceCollection.source_type == "narrative",
        SourceCollection.hierarchy_template_id == template.id,
    ))
    if collection is None:
        collection = SourceCollection(
            id=_id("collection", ontology_id, template.id),
            ontology_id=ontology_id, source_type="narrative",
            hierarchy_template_id=template.id,
            hierarchy_template_version=template.version,
            name=template.name, description=template.description or "",
            nodes=[], revision=1, archived=False,
        )
        db.add(collection)
        db.flush()
        return collection, True
    return collection, False


def _markdown_document(title: str, paragraphs: list[dict]) -> bytes:
    lines = [f"# {title}", ""]
    for paragraph in paragraphs:
        body = str(paragraph.get("text") or "").strip()
        if body:
            lines.extend((body, ""))
    return ("\n".join(lines).rstrip() + "\n").encode("utf-8")


def _new_entity_source(
    db: Session, settings, ontology_id: int, node: dict, type_name: str, prop_defs: dict,
    template: SourceHierarchy, *, scene_anchor: bool, staged: list[Path],
) -> tuple[str, str] | None:
    paragraphs, digest = _source_text(node)
    props = _properties(node, prop_defs)
    description = str(props.get("description") or "")[:10000]
    if not paragraphs and description:
        paragraphs = [{"id": _id(node["id"], "description"), "text": description}]
    if not paragraphs and not scene_anchor:
        return None

    title = _display_title(node)
    source_id = _id("entity-source", ontology_id, node["id"])
    section_id = _id("entity-section", ontology_id, node["id"])
    existing = db.get(ShreckWorldLibraryItem, source_id)
    if existing is not None:
        return source_id, section_id

    item = ShreckWorldLibraryItem(
        id=source_id, ontology_id=ontology_id, shreckworld_id=None,
        title=title, source_type="narrative", hierarchy_template_id=template.id,
        hierarchy_template_version=template.version, source_revision=1,
        authored=True, authority_tier="custom", authority_priority=100,
        pdf_path="", source_sha256=sha256(b"").hexdigest(),
        embedding_status="not_embedded", index_status="unindexed", mime_type="text/markdown",
    )
    root = SourceSection(
        id=f"source-{source_id}", parent_id=None, section_type="Source",
        title=title, order=0, content_reference=AuthoredContent(),
    )
    section = SourceSection(
        id=section_id, parent_id=root.id, section_type=type_name,
        title=title, order=0, content_reference=AuthoredContent(paragraphs=paragraphs),
        metadata=SectionMetadata(description=description, summary=description),
    )
    markdown = _markdown_document(title, paragraphs)
    if len(markdown) > MAX_TREE_BYTES:
        raise ValueError("Imported entity Markdown exceeds the source size limit")
    directory = (settings.media_root / "ontologies" / str(ontology_id) / source_id).resolve()
    media_root = settings.media_root.resolve()
    if media_root not in directory.parents:
        raise ValueError("Source document storage escaped protected media")
    directory.mkdir(parents=True, exist_ok=True)
    original = directory / f"source-{sha256(markdown).hexdigest()}.md"
    if not original.exists():
        with original.open("xb") as output:
            output.write(markdown)
            output.flush()
            os.fsync(output.fileno())
        staged.append(original)
    item.pdf_path = item.storage_path = str(original)
    item.original_filename = re.sub(r"[^a-zA-Z0-9._-]+", "-", title).strip("-.")[:100] + ".md"
    item.file_size = len(markdown)
    item.source_sha256 = sha256(markdown).hexdigest()
    item.description = description
    db.add(item)
    db.flush()

    if paragraphs:
        asset_id_value = asset_id(source_id, section_id, "markdown")
        asset_path, checksum, created = stage_asset(
            ontology_id, source_id, asset_id_value, "markdown", markdown_bytes(section), "md",
        )
        if created:
            staged.append(asset_path)
        section.metadata.markdown_asset_id = asset_id_value
        db.add(SourceAsset(
            id=asset_id_value, source_id=source_id, section_id=section_id,
            kind="markdown", storage_path=str(asset_path), mime_type="text/markdown",
            content_sha256=checksum,
        ))
    db.add(SourceOrganization(
        source_id=source_id, revision=1,
        nodes=[root.model_dump(mode="json"), section.model_dump(mode="json")],
    ))
    db.flush()
    return source_id, section_id


def _store_collection_image(settings, collection: SourceCollection, entry_id: str,
                            node: dict, staged: list[Path]) -> str | None:
    picture = _legacy_image(node.get("image"), settings.legacy_media_root)
    if picture is None:
        return None
    data, extension, _ = picture
    key = sha256(f"{collection.ontology_id}:{entry_id}".encode("utf-8")).hexdigest()[:32] + f".{extension}"
    directory = _image_root(collection, entry_id).resolve()
    if settings.media_root.resolve() not in directory.parents:
        raise ValueError("Collection image storage escaped protected media")
    target = directory / key
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        with target.open("xb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        staged.append(target)
    return key


def _archive_legacy_single_level_templates(db: Session) -> int:
    rows = db.scalars(select(SourceHierarchy).where(
        SourceHierarchy.name.in_(("Imported: Stories", "Imported: Timeline")),
        SourceHierarchy.archived.is_(False),
    )).all()
    for row in rows:
        row.archived = True
    return len(rows)


def _import_world_hierarchy(
    db: Session, settings, world: dict, paths: list[list[str]],
    types: dict, prop_defs: dict,
) -> dict[str, int]:
    ontology_id = world["ontology_id"]
    nodes = world["nodes"]
    grouped: dict[tuple[str, ...], list[list[str]]] = defaultdict(list)
    for path in paths:
        signature = tuple(types[nodes[identifier]["definition_id"]].name for identifier in path)
        if len(signature) >= MIN_NARRATIVE_LEVELS:
            grouped[signature].append(path)

    result = {"hierarchies": 0, "entries_added": 0, "documents_created": 0,
              "documents_reused": 0, "errors": 0}
    anchors = {entity_id for _, entity_id in world["scene_anchors"]}
    for signature, group_paths in grouped.items():
        staged: list[Path] = []
        try:
            template = _template_for_signature(db, signature)
            if template is None:
                continue
            collection, is_new_collection = _collection_for(db, ontology_id, template)
            result["hierarchies"] += 1
            current = [CollectionEntry.model_validate(row) for row in (collection.nodes or [])]
            by_id = {entry.id: entry for entry in current}
            graph_parents: dict[str, str | None] = {}
            children: dict[str | None, list[str]] = defaultdict(list)
            for path in group_paths:
                for position, identifier in enumerate(path):
                    parent_id = path[position - 1] if position else None
                    if identifier in graph_parents and graph_parents[identifier] != parent_id:
                        raise ValueError("narrative entity has conflicting parents")
                    graph_parents[identifier] = parent_id
            for identifier, parent in graph_parents.items():
                children[parent].append(identifier)

            new_nodes: list[CollectionEntry] = []
            mapping_rows: list[GraphSourceImport] = []
            document_cache: dict[str, tuple[str, str] | None] = {}
            old_revision = collection.revision
            graph_anchor_instances = {entity_id: instance for instance, entity_id in world["scene_anchors"]}

            def visit(identifier: str, parent_entry_id: str | None, level: int, order: int) -> None:
                node = nodes[identifier]
                entry_id = _id("collection-entry", ontology_id, identifier)
                mappings = db.scalars(select(GraphSourceImport).where(
                    GraphSourceImport.ontology_id == ontology_id,
                    GraphSourceImport.entity_instance_id == identifier,
                )).all()
                source_ids = sorted({row.source_id for row in mappings})
                if not source_ids:
                    type_def = types.get(node["definition_id"])
                    type_name = type_def.name if type_def else signature[level]
                    existing_source = db.get(ShreckWorldLibraryItem, _id("entity-source", ontology_id, identifier))
                    if identifier not in document_cache:
                        document_cache[identifier] = _new_entity_source(
                            db, settings, ontology_id, node, type_name, prop_defs, template,
                            scene_anchor=identifier in anchors, staged=staged,
                        )
                    document = document_cache[identifier]
                    if document:
                        source_ids = [document[0]]
                        if existing_source is None:
                            result["documents_created"] += 1
                        else:
                            result["documents_reused"] += 1
                        mapping_key = (ontology_id, node["instance_id"], identifier)
                        if db.get(GraphSourceImport, mapping_key) is None:
                            _, source_hash = _source_text(node)
                            db.add(GraphSourceImport(
                                ontology_id=ontology_id, instance_id=node["instance_id"],
                                entity_instance_id=identifier, source_id=document[0],
                                section_id=document[1], source_content_hash=source_hash,
                            ))
                    elif mappings:
                        result["documents_reused"] += 1

                old = by_id.get(entry_id)
                if old is not None:
                    combined_sources = sorted(set(old.source_ids).union(source_ids))
                    entry = old.model_copy(update={"source_ids": combined_sources})
                else:
                    props = _properties(node, prop_defs)
                    description = str(props.get("description") or "")[:10000]
                    image_key = _store_collection_image(settings, collection, entry_id, node, staged)
                    if parent_entry_id is None:
                        sibling_orders = [e.order for e in current + new_nodes if e.parent_id is None]
                    else:
                        sibling_orders = [e.order for e in current + new_nodes if e.parent_id == parent_entry_id]
                    entry = CollectionEntry(
                        id=entry_id, parent_id=parent_entry_id, level=level,
                        order=max(sibling_orders, default=-1) + 1 if parent_entry_id is None else order,
                        title=_display_title(node), description=description,
                        image_key=image_key, source_ids=source_ids,
                    )
                    result["entries_added"] += 1
                if old is not None and source_ids and entry.source_ids != old.source_ids:
                    result["entries_added"] += 0
                if old is None or entry.model_dump(mode="json") != old.model_dump(mode="json"):
                    new_nodes.append(entry)
                    by_id[entry_id] = entry
                for child_order, child_id in enumerate(sorted(
                    children.get(identifier, []), key=lambda key: _node_sort(nodes[key], prop_defs),
                )):
                    visit(child_id, entry_id, level + 1, child_order)

            roots = sorted(children.get(None, []), key=lambda key: _node_sort(nodes[key], prop_defs))
            for root_order, root_id in enumerate(roots):
                visit(root_id, None, 0, root_order)

            entries = list(by_id.values())
            if len(entries) > MAX_TREE_NODES:
                raise ValueError("Imported hierarchy exceeds the collection entry limit")
            previous_image_keys = {entry.id: entry.image_key for entry in current}
            validation_entries = [
                entry.model_copy(update={
                    "image_key": previous_image_keys.get(entry.id)
                    if entry.id in previous_image_keys else None,
                })
                for entry in entries
            ]
            _validate_entries(db, collection, validation_entries)
            changed = bool(new_nodes) or collection.archived
            if changed:
                if collection.revision != old_revision:
                    raise RuntimeError("Hierarchy collection changed during graph import")
                if is_new_collection:
                    collection.nodes = [entry.model_dump(mode="json") for entry in entries]
                    collection.archived = False
                    collection.revision = old_revision
                else:
                    updated = db.execute(update(SourceCollection).where(
                        SourceCollection.id == collection.id,
                        SourceCollection.revision == old_revision,
                    ).values(
                        nodes=[entry.model_dump(mode="json") for entry in entries],
                        archived=False, revision=old_revision + 1,
                    ))
                    if updated.rowcount != 1:
                        raise RuntimeError("Hierarchy collection changed during graph import")
            db.flush()
            db.commit()
        except Exception as exc:
            db.rollback()
            for path in staged:
                path.unlink(missing_ok=True)
            result["errors"] += 1
            logger.exception(
                "Graph narrative collection import failed ontology=%s hierarchy=%s (%s)",
                ontology_id, " → ".join(signature), type(exc).__name__,
            )
    return result


def _import_graph_sources_unlocked(session_factory, settings) -> dict[str, int]:
    types, relations, prop_defs = _legacy_definitions(settings.legacy_ontology_database_path)
    worlds = _graph_worlds(settings)
    summary = {"ontologies": len(worlds), "hierarchies": 0, "entries_added": 0,
               "documents_created": 0, "documents_reused": 0, "errors": 0,
               "worlds_without_scene_anchors": 0,
               "worlds_without_valid_narrative_paths": 0,
               "legacy_templates_archived": 0}
    for world in worlds:
        if not world["scene_anchors"]:
            summary["worlds_without_scene_anchors"] += 1
            continue
        paths = _narrative_paths(world, types, relations)
        if not paths:
            summary["worlds_without_valid_narrative_paths"] += 1
            logger.warning(
                "Skipping graph narrative import ontology=%s: Scene anchors do not resolve to a complete three-level hierarchy",
                world["ontology_id"],
            )
            continue
        with session_factory() as db:
            result = _import_world_hierarchy(db, settings, world, paths, types, prop_defs)
            for key in ("hierarchies", "entries_added", "documents_created", "documents_reused", "errors"):
                summary[key] += result[key]
    with session_factory() as db:
        summary["legacy_templates_archived"] = _archive_legacy_single_level_templates(db)
        db.commit()
    logger.warning("Graph narrative collection startup import: %s", summary)
    return summary


def import_graph_sources(session_factory, settings=None) -> dict[str, int]:
    """Perform one process-wide import, guarded across parallel API workers."""
    import fcntl
    settings = settings or get_settings()
    settings.media_root.mkdir(parents=True, exist_ok=True)
    lock_path = settings.media_root / ".graph-source-import.lock"
    with lock_path.open("a+b") as lock:
        try:
            fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            logger.info("Skipping graph import: another process holds the startup lock")
            return {"ontologies": 0, "hierarchies": 0, "entries_added": 0,
                    "documents_created": 0, "documents_reused": 0, "errors": 0,
                    "worlds_without_scene_anchors": 0,
                    "worlds_without_valid_narrative_paths": 0}
        try:
            return _import_graph_sources_unlocked(session_factory, settings)
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)
