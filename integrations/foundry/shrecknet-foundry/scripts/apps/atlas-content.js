// Shared presentation rules for the Atlas reader and its Foundry chat card.
export function selectedTextSource(entity, selections) {
  const text = Boolean(entity.text?.trim());
  const generated = Boolean(entity.autogenerated_text?.trim());
  if (!text && !generated) return null;
  if (!text) return "generated";
  if (!generated) return "text";
  return selections.get(entity.entity_instance_id) === "generated" ? "generated" : "text";
}

export function groupRelationships(entities, cards, definitions) {
  const groups = new Map();
  for (const entity of entities) {
    for (const relationship of entity.relationships || []) {
      const key = String(relationship.definition_id);
      if (!groups.has(key)) groups.set(key, {
        name: definitions.get(key) || "Unknown relationship type", targets: [], seen: new Set(),
      });
      const group = groups.get(key);
      const card = cards.get(relationship.target_entity_id);
      const targetKey = card ? `${card.instanceId}:${card.typeId}` : relationship.target_entity_id;
      if (group.seen.has(targetKey)) continue;
      group.seen.add(targetKey);
      group.targets.push(card || { unavailable: true, name: "Related page unavailable" });
    }
  }
  return [...groups.values()].map(({ name, targets }) => ({ name, targets }));
}

export function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

export function safeImageUrl(value) {
  try {
    const url = new URL(value);
    return ["https:", "http:"].includes(url.protocol) && !url.username && !url.password ? url.href : null;
  } catch (_) { return null; }
}

// Section HTML must pass through the document sanitizer before reaching here.
export function renderAtlasChat(page, sections) {
  const imageUrl = safeImageUrl(page.pageImageUrl);
  const relationships = page.relationshipGroups.map((group) =>
    `<section><h4>${escapeHtml(group.name)}</h4><ul>${group.targets.map((target) =>
      `<li>${escapeHtml(target.name)}${target.unavailable ? "" : ` · ${escapeHtml(target.typeName)}`}</li>`,
    ).join("")}</ul></section>`,
  ).join("");
  return `<article class="shrecknet-chat-record"><h2>${escapeHtml(page.displayName)}</h2>${imageUrl ? `<img src="${escapeHtml(imageUrl)}" alt="" style="max-width:100%;">` : ""}${sections.map((section) =>
    `<section><h3>${escapeHtml(section.name)}</h3>${section.source ? `<p>${section.source === "text" ? "Original text" : "Generated text"}</p>` : ""}<div>${section.html || "<p>No document text available.</p>"}</div></section>`,
  ).join("")}${relationships ? `<h3>Relationships</h3>${relationships}` : ""}</article>`;
}
