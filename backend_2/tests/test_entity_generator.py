def test_format_properties_catalog():
    """Test that the properties catalog is formatted correctly."""
    generator = EntityGenerator(
        llm_client=StubLLMForGeneration("{}"),
        model_policy=StubPolicyForGeneration(),
    )

    properties = [
        {
            "id": 1,
            "name": "age",
            "description": "Age in years",
            "data_type": "number",
            "cardinality": "one",
        },
        {
            "id": 2,
            "name": "titles",
            "description": "Noble titles",
            "data_type": "text",
            "cardinality": "many",
        },
    ]

    catalog = generator._format_properties_catalog(properties)

    assert "ID 1: age (number, one)" in catalog
    assert "Age in years" in catalog
    assert "ID 2: titles (text, many)" in catalog
    assert "Noble titles" in catalog


