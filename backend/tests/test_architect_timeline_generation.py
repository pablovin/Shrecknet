def test_dedup_timeline_events_limits_and_sorts():
    events = [
        {"title": "Battle Starts", "description": "The battle begins.", "order": 2, "chunk_index": 0, "chunk_order": 2, "temporal_hint": 0.0},
        {"title": "Battle Starts", "description": "The battle begins (duplicate).", "order": 3, "chunk_index": 0, "chunk_order": 3, "temporal_hint": 0.0},
        {"title": "Arrival", "description": "They arrive.", "order": 1, "chunk_index": 0, "chunk_order": 1, "temporal_hint": 0.0},
        {"title": "Aftermath", "description": "The dust settles.", "order": 4, "chunk_index": 0, "chunk_order": 4, "temporal_hint": 0.0},
    ]
    result = dedup_timeline_events(events, max_events=2)
    assert len(result) == 2
    titles = [item["title"] for item in result]
    assert len(set(titles)) == 2
