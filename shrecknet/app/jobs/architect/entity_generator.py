logger = logging.getLogger(__name__)

# Regex pattern to remove markdown code block delimiters (e.g., ```html, ```javascript, ```)
MARKDOWN_CODE_BLOCK_PATTERN = r"```[a-zA-Z]*\s*\n?(.*?)\n?```"


class EntityGenerator:
    """Generates entities and updates with properties/relationships from text."""

    def __init__(
        self,
        llm_client: ShreckLLMClient,
        model_policy: ModelPolicy,
        *,
        concurrent_extractions: int = 4,
    ) -> None:
        self.llm_client = llm_client
        self.model_policy = model_policy
        self.concurrent_extractions = max(1, concurrent_extractions)

    async def generate_new_entities(
        self,
        *,
        proposals: list[dict[str, Any]],
        entity_definitions_map: dict[int, dict[str, Any]],
        original_text: str,
        author_type: str,
        author_id: str,
    ) -> list[tuple[str, OntologyInstanceEntityCreate, list[dict[str, Any]]]]:
        """Generate new entity instances from approved proposals."""
        semaphore = asyncio.Semaphore(self.concurrent_extractions)

        async def process_new_entity(
            proposal: dict[str, Any],
        ) -> tuple[str, OntologyInstanceEntityCreate, list[dict[str, Any]]] | None:
            async with semaphore:
                try:
                    entity, relationships = await self._generate_new_entity(
                        proposal=proposal,
                        entity_definitions_map=entity_definitions_map,
                        original_text=original_text,
                        author_type=author_type,
                        author_id=author_id,
                    )
                    return proposal["id"], entity, relationships
                except Exception as exc:
                    logger.error(
                        "Failed to generate new entity for proposal %s: %s",
                        proposal.get("id"),
                        exc,
                        exc_info=True,
                    )
                    return None

        results = await asyncio.gather(*(process_new_entity(p) for p in proposals))
        return [r for r in results if r is not None]

    async def _generate_new_entity(
        self,
        *,
        proposal: dict[str, Any],
        entity_definitions_map: dict[int, dict[str, Any]],
        original_text: str,
        author_type: str,
        author_id: str,
    ) -> tuple[OntologyInstanceEntityCreate, list[dict[str, Any]]]:
        """Generate a single new entity."""
        entity_def_id = (
            proposal.get("corrected_entity_definition_id")
            or proposal["entity_definition_id"]
        )
        alias = proposal.get("corrected_alias") or proposal["alias"]
        chunks = proposal.get("chunks", [])

        entity_def = entity_definitions_map.get(entity_def_id)
        if not entity_def:
            raise ValueError(f"Entity definition {entity_def_id} not found")

        author_enum = self._normalize_author_type(author_type)

        # Extract auto-generatable properties and relationships
        extracted = await self._extract_properties_and_relationships(
            entity_definition_id=entity_def_id,
            entity_alias=alias,
            entity_type_name=entity_def["name"],
            properties_catalog=entity_def["properties"],
            relationships_catalog=entity_def["relationships"],
            chunks=chunks,
            original_text=original_text,
            is_update=False,
        )

        logger.debug(
            "architect_generation: extracted new entity props=%d rels=%d summary=%s for proposal=%s alias=%s",
            len(extracted.properties),
            len(extracted.relationships),
            bool(extracted.autogenerated_summary),
            proposal.get("id"),
            alias,
        )

        # Build entity create payload
        properties = [
            OntologyInstancePropertyValue(definition_id=p.definition_id, value=p.value)
            for p in extracted.properties
        ]

        relationships = [
            {
                "definition_id": rel.definition_id,
                "target_alias": rel.target_alias,
                "target_entity_instance_id": rel.target_entity_instance_id,
                "justification": rel.justification,
            }
            for rel in extracted.relationships
        ]

        # Note: Relationships will be added in a second pass
        # For now, we just collect them for later processing
        entity_payload = OntologyInstanceEntityCreate(
            definition_id=entity_def_id,
            alias=alias,
            text="",  # No user text for auto-generated entities
            autogenerated_text=extracted.autogenerated_summary or "",
            author_type=author_enum,
            author_id=author_id,
            properties=properties,
            relationships=[],  # Will be populated in second pass
        )
        return entity_payload, relationships

    async def update_existing_entities(
        self,
        *,
        proposals: list[dict[str, Any]],
        entity_definitions_map: dict[int, dict[str, Any]],
        existing_entities_map: dict[str, dict[str, Any]],
        original_text: str,
        author_type: str,
        author_id: str,
    ) -> list[dict[str, Any]]:
        """Update existing entities with new information from proposals."""
        semaphore = asyncio.Semaphore(self.concurrent_extractions)

        async def process_update(proposal: dict[str, Any]) -> dict[str, Any] | None:
            async with semaphore:
                try:
                    return await self._update_existing_entity(
                        proposal=proposal,
                        entity_definitions_map=entity_definitions_map,
                        existing_entities_map=existing_entities_map,
                        original_text=original_text,
                        author_type=author_type,
                        author_id=author_id,
                    )
                except Exception as exc:
                    logger.error(
                        "Failed to update entity for proposal %s: %s",
                        proposal.get("id"),
                        exc,
                        exc_info=True,
                    )
                    return None

        results = await asyncio.gather(*(process_update(p) for p in proposals))
        return [r for r in results if r is not None]

    async def _update_existing_entity(
        self,
        *,
        proposal: dict[str, Any],
        entity_definitions_map: dict[int, dict[str, Any]],
        existing_entities_map: dict[str, dict[str, Any]],
        original_text: str,
        author_type: str,
        author_id: str,
    ) -> dict[str, Any]:
        """Update a single existing entity."""
        entity_instance_id = proposal["entity_instance_id"]
        chunks = proposal.get("chunks", [])

        existing_entity = existing_entities_map.get(entity_instance_id)
        if not existing_entity:
            raise ValueError(f"Entity instance {entity_instance_id} not found")

        entity_def_id = existing_entity["definition_id"]
        entity_def = entity_definitions_map.get(entity_def_id)
        if not entity_def:
            raise ValueError(f"Entity definition {entity_def_id} not found")

        # Extract new properties and relationships
        extracted = await self._extract_properties_and_relationships(
            entity_definition_id=entity_def_id,
            entity_alias=existing_entity.get("alias", ""),
            entity_type_name=entity_def["name"],
            properties_catalog=entity_def["properties"],
            relationships_catalog=entity_def["relationships"],
            chunks=chunks,
            original_text=original_text,
            is_update=True,
            existing_text=existing_entity.get("text", ""),
            existing_autogenerated_text=existing_entity.get("autogenerated_text", ""),
            existing_properties=existing_entity.get("properties", []),
            existing_relationships=existing_entity.get("relationships", []),
        )

        normalized_author = self._normalize_author_type(author_type).value

        logger.debug(
            "architect_generation: extracted update props=%d rels=%d summary=%s for proposal=%s entity=%s",
            len(extracted.new_properties),
            len(extracted.new_relationships),
            bool(extracted.updated_autogenerated_summary),
            proposal.get("id"),
            entity_instance_id,
        )

        return {
            "proposal_id": proposal.get("id"),
            "entity_instance_id": entity_instance_id,
            "new_properties": extracted.new_properties,
            "new_relationships": extracted.new_relationships,
            "updated_autogenerated_summary": extracted.updated_autogenerated_summary,
            "author_type": normalized_author,
            "author_id": author_id,
        }

    @staticmethod
    def _normalize_author_type(author_type: str) -> AuthorType:
        value = (author_type or "").strip().lower()
        if value in {"human", "user"}:
            return AuthorType.HUMAN
        if value in {"agent", "ai", "assistant"}:
            return AuthorType.AGENT
        raise ValueError(f"Unsupported author_type '{author_type}'")

    async def _extract_properties_and_relationships(
        self,
        *,
        entity_definition_id: int,
        entity_alias: str,
        entity_type_name: str,
        properties_catalog: list[dict[str, Any]],
        relationships_catalog: list[dict[str, Any]],
        chunks: list[str],
        related_entities: list[dict[str, Any]] | None = None,
        original_text: str = "",
        is_update: bool,
        existing_text: str = "",
        existing_autogenerated_text: str = "",
        existing_properties: list[dict[str, Any]] | None = None,
        existing_relationships: list[dict[str, Any]] | None = None,
        debug_job_id: int | None = None,
        debug_entity_id: str | None = None,
        debug_anomalies: list[str] | None = None,
        debug_context_package: dict[str, Any] | None = None,
        update_response_mode: str = "legacy",
    ) -> PropertyExtractionResponse | PropertyUpdateResponse | StrictPropertyUpdateResponse:
        """Extract properties and relationships from text chunks using LLM."""
        combined_chunks = "\n\n---\n\n".join(chunks) if chunks else ""

        # Format catalogs
        props_catalog_str = self._format_properties_catalog(properties_catalog)
        rels_catalog_str = self._format_relationships_catalog(relationships_catalog)
        related_entities_str = self._format_related_entities(related_entities or [])
        scenes_context_str = self._format_scenes_context(
            (debug_context_package or {}).get("scenes") or []
        )

        logger.info(
            "architect.generate enrichment_prompt entity=%s property_catalog_count=%d relationship_catalog_count=%d related_entities_count=%d chunk_count=%d",
            entity_alias,
            len(properties_catalog or []),
            len(relationships_catalog or []),
            len(related_entities or []),
            len(chunks or []),
        )
        if not properties_catalog:
            logger.warning(
                "architect.generate enrichment_prompt entity=%s has_empty_property_catalog",
                entity_alias,
            )
        if not relationships_catalog:
            logger.warning(
                "architect.generate enrichment_prompt entity=%s has_empty_relationship_catalog",
                entity_alias,
            )

        # Always pass existing state so extraction and update semantics stay in one step.
        existing_props_str = self._format_existing_properties(
            existing_properties or [], properties_catalog
        )
        existing_rels_str = self._format_existing_relationships(
            existing_relationships or [], relationships_catalog
        )

        prompt = ARCHITECT_PROPERTY_UPDATE_PROMPT.format(
            entity_alias=entity_alias,
            entity_type_name=entity_type_name,
            existing_properties=existing_props_str,
            existing_relationships=existing_rels_str,
            properties_catalog=props_catalog_str,
            relationships_catalog=rels_catalog_str,
            related_entities=related_entities_str,
            scenes_context=scenes_context_str,
            combined_chunks=combined_chunks or "(no text)",
            existing_text=existing_text or "(no text)",
            existing_autogenerated_text=existing_autogenerated_text or "(no summary)",
            entity_definition_id=entity_definition_id,
        )

        model = self.model_policy.get_model(LLMTask.ARCHITECT_EXTRACT)
        debug_payload: dict[str, Any] = {
            "entity_alias": entity_alias,
            "entity_id": debug_entity_id,
            "entity_definition_id": entity_definition_id,
            "entity_type_name": entity_type_name,
            "is_update": is_update,
            "anomalies": debug_anomalies or [],
            "context_package": debug_context_package or {},
            "llm_request": {
                "model": model,
                "temperature": 0.1,
                "messages": [{"role": "user", "content": prompt}],
            },
            "llm_response": {
                "raw_response": None,
            },
            "processing_status": "processing",
        }
        response_text = await self.llm_client.chat(
            model=model,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.1,
            usage_tag="architect.generate.enrichment",
        )
        debug_payload["llm_response"]["raw_response"] = response_text

        parsed = self._parse_extraction_response(
            response_text=response_text,
            is_update=is_update,
            update_response_mode=update_response_mode,
        )

        if parsed is None:
            debug_payload["processing_status"] = "failed_parse"
            self._write_enrichment_debug_file(
                debug_job_id=debug_job_id,
                entity_alias=entity_alias,
                entity_id=debug_entity_id,
                payload=debug_payload,
            )
            return (
                (
                    StrictPropertyUpdateResponse()
                    if is_update and update_response_mode == "strict_name_based"
                    else PropertyUpdateResponse()
                )
                if is_update
                else PropertyExtractionResponse()
            )

        # Ensure we always have a usable summary even if the model omits one
        if is_update:
            if not parsed.updated_autogenerated_summary:
                parsed.updated_autogenerated_summary = self._fallback_summary(
                    combined_chunks,
                    existing_autogenerated_text,
                    existing_text,
                )
        else:
            if not parsed.autogenerated_summary:
                parsed.autogenerated_summary = self._fallback_summary(
                    combined_chunks
                )

        debug_payload["processing_status"] = "parsed"
        debug_payload["parsed_payload"] = (
            parsed.model_dump()
            if hasattr(parsed, "model_dump")
            else {}
        )
        self._write_enrichment_debug_file(
            debug_job_id=debug_job_id,
            entity_alias=entity_alias,
            entity_id=debug_entity_id,
            payload=debug_payload,
        )

        return parsed

