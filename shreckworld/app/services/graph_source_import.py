"""Import scene-backed narrative graph trees into world hierarchy collections.

Scenes select the narratives to import, but entity ancestry is reconstructed
across the whole ontology because related entities can belong to different
OntologyInstance pages. Sources are attached to collection entries; graph data
and legacy SQLite/media inputs remain read-only.
"""
