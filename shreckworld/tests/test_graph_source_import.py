def _legacy(path: Path) -> None:
    with sqlite3.connect(path) as conn:
        conn.executescript("""
            CREATE TABLE ontology_entities(id INTEGER PRIMARY KEY, name TEXT);
            CREATE TABLE entity_relationships(id INTEGER PRIMARY KEY, entity_id INTEGER,
                destiny_entity_id INTEGER, name TEXT);
            CREATE TABLE entity_properties(id INTEGER PRIMARY KEY, entity_id INTEGER, name TEXT);
            INSERT INTO ontology_entities VALUES(1, 'Adventure'), (2, 'Story Arc'), (3, 'Story');
            INSERT INTO entity_relationships VALUES(7, 1, 2, 'contains'),
                                                    (8, 2, 3, 'contains');
        """)


def _node(id: str, definition_id: int, title: str, text: str = "", image: str | None = None) -> dict:
    return dict(id=id, definition_id=definition_id, title=title, text=text, autogenerated_text="",
                image=image, properties="{}", created_date="")


def _page(extra: bool = False) -> dict:
    nodes = {
        "a": _node("a", 1, "The Wolf of Midnight", "Adventure introduction"),
        "arc": _node("arc", 2, "Arc 1 - Trouble", "The first arc"),
        "s1": _node("s1", 3, "What Can Go Wrong?", "First story", "/media/scene/story.png"),
        "s2": _node("s2", 3, "What Can Go Wrong Again?", "Second story"),
    }
    leaves = {"s1", "s2"}
    edges = [("a", "arc", 7), ("arc", "s1", 8), ("arc", "s2", 8)]
    if extra:
        nodes["s3"] = _node("s3", 3, "One More Time", "Third story")
        edges.append(("arc", "s3", 8))
        leaves.add("s3")
    return dict(ontology_id=42, instance_id="instance-1", nodes=nodes, edges=edges, leaves=leaves)


def test_graph_import_is_idempotent_and_adds_new_stories(tmp_path, monkeypatch):
    legacy = tmp_path / "legacy.db"
    _legacy(legacy)
    legacy_media = tmp_path / "legacy_media"
    (legacy_media / "scene").mkdir(parents=True)
    (legacy_media / "scene" / "story.png").write_bytes(bytes.fromhex("89504e470d0a1a0a") + b"sample")
    media = tmp_path / "media"
    settings = SimpleNamespace(
        legacy_ontology_database_path=legacy, legacy_media_root=legacy_media,
        media_root=media)
    monkeypatch.setattr(assets, "get_settings", lambda: settings)
    monkeypatch.setattr(workspace, "get_settings", lambda: settings)
    engine = create_engine("sqlite+pysqlite:///" + str(tmp_path / "sources.db"))
    Base.metadata.create_all(engine)
    factory = sessionmaker(bind=engine)
    with Session(engine) as db:
        db.add(SourceHierarchy(id="rpg-campaign", version=1, name="RPG Campaign",
            section_types=["Adventure", "Story Arc", "Story"],
            source_type="narrative", archived=False))
        db.commit()

    monkeypatch.setattr(importer, "_graph_pages", lambda settings: [_page()])
    first = importer.import_graph_sources(factory, settings)
    assert first["imported"] == 1 and first["errors"] == 0
    with Session(engine) as db:
        item = db.scalar(select(ShreckWorldLibraryItem))
        assert item is not None and item.source_type == "narrative"
        assert item.hierarchy_template_id == "rpg-campaign"
        original = workspace.get_organization(db, item)
        assert len(original.nodes) == 4
        assert original.nodes[0].title == "The Wolf of Midnight"
        assert len(db.scalars(select(SourceAsset)).all()) == 5  # 4 Markdown files + 1 image
        assert len(db.scalars(select(GraphSourceImport)).all()) == 4
        story = next(node for node in original.nodes if node.title == "What Can Go Wrong?")
        md = db.get(SourceAsset, story.metadata.markdown_asset_id)
        assert "First story" in Path(md.storage_path).read_text()
        image = db.get(SourceAsset, story.metadata.image_asset_id)
        assert Path(image.storage_path).is_file()
        assert assets.read_asset(db, item.id, image.id).id == image.id
        from fastapi import HTTPException
        import pytest
        with pytest.raises(HTTPException) as wrong_source:
            assets.read_asset(db, "some-other-source", image.id)
        assert wrong_source.value.status_code == 404
        source_id = item.id

    second = importer.import_graph_sources(factory, settings)
    assert second["imported"] == 0 and second["errors"] == 0
    monkeypatch.setattr(importer, "_graph_pages", lambda settings: [_page(extra=True)])
    third = importer.import_graph_sources(factory, settings)
    assert third["imported"] == 1 and third["errors"] == 0
    with Session(engine) as db:
        item = db.get(ShreckWorldLibraryItem, source_id)
        org = workspace.get_organization(db, item)
        assert len(org.nodes) == 5
        assert item.source_revision == 2
        assert len(db.scalars(select(GraphSourceImport)).all()) == 5
        assert len(db.scalars(select(SourceAsset)).all()) == 6
    engine.dispose()


def test_ambiguous_narrative_parent_is_not_guessed():
    types = {1: importer.LegacyType(1, "Adventure"),
             2: importer.LegacyType(2, "Story Arc"),
             3: importer.LegacyType(3, "Story")}
    nodes = {"s": _node("s", 3, "A Story"),
             "a": _node("a", 2, "Arc One"),
             "b": _node("b", 2, "Arc Two")}
    definitions = {7: {"entity_id": 2, "destiny_entity_id": 3}}
    import pytest
    with pytest.raises(ValueError, match="ambiguous"):
        importer._ancestry("s", nodes, [("a", "s", 7), ("b", "s", 7)], types, definitions)


def test_imported_node_markdown_follows_editor_without_overwriting_edits(tmp_path, monkeypatch):
    from app.schemas.sources import OrganizationInput, SourceSection
    legacy = tmp_path / "legacy.db"
    _legacy(legacy)
    settings = SimpleNamespace(legacy_ontology_database_path=legacy,
        legacy_media_root=tmp_path / "not-present", media_root=tmp_path / "media")
    monkeypatch.setattr(assets, "get_settings", lambda: settings)
    monkeypatch.setattr(workspace, "get_settings", lambda: settings)
    engine = create_engine("sqlite+pysqlite:///" + str(tmp_path / "source.db"))
    Base.metadata.create_all(engine)
    factory = sessionmaker(bind=engine)
    monkeypatch.setattr(importer, "_graph_pages", lambda _: [_page()])
    assert importer.import_graph_sources(factory, settings)["imported"] == 1
    with Session(engine) as db:
        item = db.scalar(select(ShreckWorldLibraryItem))
        org = workspace.get_organization(db, item)
        changed = [SourceSection.model_validate(node.model_dump()) for node in org.nodes]
        story = next(node for node in changed if node.title == "What Can Go Wrong?")
        asset = db.get(SourceAsset, story.metadata.markdown_asset_id)
        old_path = Path(asset.storage_path)
        story.content_reference.paragraphs[0].text = "My revised adventure"
        # Simulates a legacy editor that does not round-trip new asset IDs.
        story.metadata.markdown_asset_id = None
        workspace.save_organization(db, item, OrganizationInput(
            expected_revision=item.source_revision, nodes=changed))
        db.refresh(asset)
        assert Path(asset.storage_path).read_text(encoding="utf-8").strip() == "My revised adventure"
        assert old_path.exists() and "First story" in old_path.read_text(encoding="utf-8")
    assert importer.import_graph_sources(factory, settings)["imported"] == 0
    with Session(engine) as db:
        item = db.scalar(select(ShreckWorldLibraryItem))
        story = next(node for node in workspace.get_organization(db, item).nodes
                     if node.title == "What Can Go Wrong?")
        assert story.content_reference.paragraphs[0].text == "My revised adventure"
    engine.dispose()


