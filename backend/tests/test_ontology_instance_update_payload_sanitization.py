from __future__ import annotations

from datetime import datetime, timezone
from types import SimpleNamespace

from app.models.ontology import AuthorType
from app.schemas.ontology_instance import (
    OntologyInstanceEntityCreate,
    OntologyInstancePropertyValue,
    OntologyInstanceRelationshipCreate,
)
from app.services.ontology_instance_service import OntologyInstanceService


def _entity(
    *,
    definition_id: int,
    alias: str,
    property_ids: list[int],
    relationship_ids: list[int],
) -> OntologyInstanceEntityCreate:
    return OntologyInstanceEntityCreate(
        definition_id=definition_id,
        alias=alias,
        text=f"{alias} text",
        node_avatar_url=None,
        autogenerated_text=None,
        created_date=datetime.now(timezone.utc),
        last_updated_date=datetime.now(timezone.utc),
        author_type=AuthorType.HUMAN,
        author_id=f"author-{alias}",
        properties=[
            OntologyInstancePropertyValue(definition_id=prop_id, value=f"v-{prop_id}")
            for prop_id in property_ids
        ],
        relationships=[
            OntologyInstanceRelationshipCreate(
                definition_id=rel_id,
                target_alias="beta",
                data={},
            )
            for rel_id in relationship_ids
        ],
    )


def test_update_payload_sanitization_drops_invalid_property_and_relationship_ids():
    service = OntologyInstanceService(sql_session=None, graph_session=None)  # type: ignore[arg-type]
    definitions = {
        10: {
            "properties": {1: object()},
            "relationships": {100: SimpleNamespace(destiny_entity_id=11)},
        },
        11: {
            "properties": {2: object()},
            "relationships": {},
        },
    }
    entities = [
        _entity(
            definition_id=10,
            alias="alpha",
            property_ids=[1, 2],  # 2 is invalid for entity definition 10
            relationship_ids=[100, 999],  # 999 is invalid for entity definition 10
        ),
        _entity(
            definition_id=11,
            alias="beta",
            property_ids=[2],
            relationship_ids=[],
        ),
    ]

    sanitized = service._sanitize_entities_payload_for_update(entities, definitions)

    assert [prop.definition_id for prop in sanitized[0].properties] == [1]
    assert [rel.definition_id for rel in sanitized[0].relationships] == [100]
    assert [prop.definition_id for prop in sanitized[1].properties] == [2]

    # Should validate after sanitization.
    service._validate_entities_payload(sanitized, definitions)
