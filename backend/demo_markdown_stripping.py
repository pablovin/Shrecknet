#!/usr/bin/env python3
"""
Demonstration script showing how the markdown code block stripping works.

This simulates what happens when the LLM returns text wrapped in markdown code blocks.
"""

import re


def _strip_markdown_code_blocks(text: str) -> str:
    """
    Remove markdown code block delimiters from text.

    This is needed because LLMs sometimes wrap HTML/text content in markdown code blocks,
    which makes them unparsable on the frontend.

    Handles code blocks with any language identifier (e.g., ```html, ```javascript, ```css)
    or no identifier (e.g., ```).
    """
    if not text:
        return ""
    # Remove markdown code blocks with any optional language identifier
    # Use DOTALL flag to match across newlines
    cleaned = re.sub(
        r"```[a-zA-Z]*\s*\n?(.*?)\n?```", r"\1", text, flags=re.DOTALL | re.IGNORECASE
    )
    return cleaned.strip()


def demonstrate_fix():
    """Demonstrate the fix with example LLM responses."""

    print("=" * 80)
    print("MARKDOWN CODE BLOCK STRIPPING DEMONSTRATION")
    print("=" * 80)
    print()

    # Example 1: Autogenerated summary with HTML
    print("Example 1: Autogenerated Entity Summary")
    print("-" * 80)
    llm_response = """```html
<article>
<h2>Jessie Williams</h2>
<section>
<h3>Background</h3>
<p>Jessie Williams, initially a young history student, evolves into a determined investigator navigating the aftermath of traumatic events while uncovering supernatural evidence.</p>
</section>
<section>
<h3>Journey and Growth</h3>
<p>Her journey culminates in her acceptance of a role within the Brotherhood in Paris, showcasing her growth as she confronts unseen horrors and communicates vital next steps to her peers.</p>
</section>
<section>
<h3>Commitment and Resolve</h3>
<p>This steadfast commitment to facing darkness highlights her resolve to prove her worth amidst the challenges posed by the Mythos.</p>
</section>
</article>
```"""

    print("BEFORE (with markdown delimiters):")
    print(llm_response[:200] + "..." if len(llm_response) > 200 else llm_response)
    print()

    cleaned = _strip_markdown_code_blocks(llm_response)
    print("AFTER (clean HTML):")
    print(cleaned[:200] + "..." if len(cleaned) > 200 else cleaned)
    print()
    print()

    # Example 2: Timeline event description
    print("Example 2: Timeline Event Description")
    print("-" * 80)
    timeline_description = """```html
<p>Jessie discovers ancient texts in the university library, uncovering references to the Brotherhood and its connection to the Mythos. This marks the beginning of her transformation from student to investigator.</p>
```"""

    print("BEFORE:")
    print(timeline_description)
    print()

    cleaned = _strip_markdown_code_blocks(timeline_description)
    print("AFTER:")
    print(cleaned)
    print()
    print()

    # Example 3: Relationship justification
    print("Example 3: Relationship Justification")
    print("-" * 80)
    justification = """```
Jessie mentors Sarah in understanding the ancient texts and navigating the dangers of investigating the Mythos.
```"""

    print("BEFORE:")
    print(justification)
    print()

    cleaned = _strip_markdown_code_blocks(justification)
    print("AFTER:")
    print(cleaned)
    print()
    print()

    # Example 4: Plain text (should remain unchanged)
    print("Example 4: Plain Text (No Markdown)")
    print("-" * 80)
    plain_text = "This is plain text without any markdown code blocks."

    print("BEFORE:")
    print(plain_text)
    print()

    cleaned = _strip_markdown_code_blocks(plain_text)
    print("AFTER:")
    print(cleaned)
    print()

    print("=" * 80)
    print("✓ All examples processed successfully!")
    print("=" * 80)


if __name__ == "__main__":
    demonstrate_fix()
