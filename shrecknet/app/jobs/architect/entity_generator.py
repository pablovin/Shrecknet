    @staticmethod
    def _resolve_architect_generate_debug_dirs(*, debug_job_id: int) -> list[Path]:
        import os

        module_root = Path(__file__).resolve().parents[3]
        cwd = Path.cwd()
        data_root = Path(os.getenv("SHRECKNET_DATA_DIR", "")).expanduser() if os.getenv("SHRECKNET_DATA_DIR") else None
        candidates = [
            *( [data_root / "local_test" / "architect" / "generate" / str(debug_job_id)] if data_root else [] ),
            module_root / "databases" / "local_test" / "architect" / "generate" / str(debug_job_id),
            cwd / "shrecknet" / "databases" / "local_test" / "architect" / "generate" / str(debug_job_id),
            cwd / "databases" / "local_test" / "architect" / "generate" / str(debug_job_id),
        ]
        # Deduplicate while preserving order.
        unique: list[Path] = []
        seen: set[str] = set()
        for candidate in candidates:
            key = str(candidate.resolve()) if candidate.exists() else str(candidate)
            if key in seen:
                continue
            seen.add(key)
            unique.append(candidate)
        return unique

    def _parse_extraction_response(
        self, *, response_text: str, is_update: bool, update_response_mode: str
    ) -> PropertyExtractionResponse | PropertyUpdateResponse | StrictPropertyUpdateResponse | None:
        """Parse the LLM response and return the typed payload or None on failure."""
        try:
            json_block = self._extract_json_block(response_text)
            payload = json.loads(json_block)

            # Strip markdown code blocks from text fields in the response
            if "autogenerated_summary" in payload and isinstance(
                payload["autogenerated_summary"], str
            ):
                payload["autogenerated_summary"] = self._strip_markdown_code_blocks(
                    payload["autogenerated_summary"]
                )
            if "updated_autogenerated_summary" in payload and isinstance(
                payload["updated_autogenerated_summary"], str
            ):
                payload["updated_autogenerated_summary"] = (
                    self._strip_markdown_code_blocks(
                        payload["updated_autogenerated_summary"]
                    )
                )

            # Strip markdown from relationship justifications (legacy mode only).
            for rel in payload.get("relationships", []) or payload.get("new_relationships", []):
                if isinstance(rel.get("justification"), str):
                    rel["justification"] = self._strip_markdown_code_blocks(
                        rel["justification"]
                    )

            # Strip markdown from property values if they're text.
            for prop in payload.get("properties", []) or payload.get(
                "new_properties", []
            ):
                if isinstance(prop.get("value"), str):
                    prop["value"] = self._strip_markdown_code_blocks(prop["value"])
            for prop in payload.get("properties_update", []):
                if isinstance(prop.get("property_value"), str):
                    prop["property_value"] = self._strip_markdown_code_blocks(
                        prop["property_value"]
                    )

            def _coerce_int(value: Any) -> int | None:
                if isinstance(value, bool):
                    return None
                if isinstance(value, int):
                    return value
                if isinstance(value, str) and value.strip().isdigit():
                    return int(value.strip())
                return None

            def _sanitize_items(items: Any) -> list[dict[str, Any]]:
                if not isinstance(items, list):
                    return []
                return [item for item in items if isinstance(item, dict)]

            # Be tolerant to partial LLM drift: drop malformed items instead of
            # failing the whole payload (which would also lose summary updates).
            for key in ("properties", "new_properties"):
                sanitized: list[dict[str, Any]] = []
                for item in _sanitize_items(payload.get(key)):
                    definition_id = _coerce_int(item.get("definition_id"))
                    if definition_id is None:
                        continue
                    sanitized.append({**item, "definition_id": definition_id})
                if key in payload:
                    payload[key] = sanitized

            for key in ("relationships", "new_relationships"):
                sanitized = []
                for item in _sanitize_items(payload.get(key)):
                    definition_id = _coerce_int(item.get("definition_id"))
                    if definition_id is None:
                        continue
                    sanitized.append({**item, "definition_id": definition_id})
                if key in payload:
                    payload[key] = sanitized

            if is_update:
                if update_response_mode == "strict_name_based":
                    allowed_keys = {
                        "properties_update",
                        "relationships_update",
                        "updated_autogenerated_summary",
                    }
                    if any(key not in allowed_keys for key in payload.keys()):
                        raise ValueError("Unexpected keys in strict update payload")
                    return StrictPropertyUpdateResponse.model_validate(payload)
                return PropertyUpdateResponse.model_validate(payload)
            if "properties" not in payload and "new_properties" in payload:
                payload["properties"] = payload.get("new_properties", [])
            if "relationships" not in payload and "new_relationships" in payload:
                payload["relationships"] = payload.get("new_relationships", [])
            if (
                "autogenerated_summary" not in payload
                and "updated_autogenerated_summary" in payload
            ):
                payload["autogenerated_summary"] = payload.get(
                    "updated_autogenerated_summary"
                )
            return PropertyExtractionResponse.model_validate(payload)
        except Exception as exc:
            logger.warning(
                "Failed to parse property extraction response: %s\nResponse: %s",
                exc,
                response_text,
            )
            return None

    @staticmethod
    def _strip_markdown_code_blocks(text: str | None) -> str:
        """
        Remove markdown code block delimiters from text.

        This is needed because LLMs sometimes wrap HTML/text content in markdown code blocks,
        which makes them unparsable on the frontend.

        Handles code blocks with any language identifier (e.g., ```html, ```javascript, ```css)
        or no identifier (e.g., ```).

        Args:
            text: The text to clean, may be None

        Returns:
            Clean text without markdown code block delimiters
        """
        if not text:
            return ""
        # Remove markdown code blocks with any optional language identifier
        # Use DOTALL flag to match across newlines
        cleaned = re.sub(
            MARKDOWN_CODE_BLOCK_PATTERN,
            r"\1",
            text,
            flags=re.DOTALL | re.IGNORECASE,
        )
        return cleaned.strip()

    @staticmethod
    def _fallback_summary(*texts: str | None, limit: int = 500) -> str:
        """Build a lightweight fallback summary from provided text snippets."""
        chosen = next((t for t in texts if t), "")
        collapsed = " ".join(chosen.split())
        if len(collapsed) > limit:
            return collapsed[: limit - 1] + "…"
        return collapsed

    @staticmethod
    def _extract_json_block(raw: str) -> str:
        """Extract JSON object from LLM response."""
        start = raw.find("{")
        end = raw.rfind("}")
        if start == -1 or end == -1 or end <= start:
            raise ValueError("No JSON object found in LLM response")
        return raw[start : end + 1]

    @staticmethod
    def _format_properties_catalog(properties: list[dict[str, Any]]) -> str:
        """Format properties catalog for prompt."""
        if not properties:
            return "(no auto-generatable properties)"
        lines = []
        for prop in properties:
            desc = (prop.get("description") or "").strip()
            lines.append(
                f"- ID {prop['id']}: {prop['name']} ({prop['data_type']}, {prop['cardinality']}) - {desc or 'No description'}"
            )
        return "\n".join(lines)

    @staticmethod
    def _format_relationships_catalog(relationships: list[dict[str, Any]]) -> str:
        """Format relationships catalog for prompt."""
        if not relationships:
            return "(no auto-generatable relationships)"
        lines = []
        for rel in relationships:
            desc = (rel.get("description") or "").strip()
            target = rel.get("destiny_entity_name", "any entity")
            lines.append(
                f"- ID {rel['id']}: {rel['name']} (related to entity type: {target}) - {desc or 'No description'}"
            )
        return "\n".join(lines)

    @staticmethod
    def _format_existing_properties(
        existing: list[dict[str, Any]], catalog: list[dict[str, Any]]
    ) -> str:
        """Format existing properties for prompt."""
        if not existing:
            return "(none)"
        catalog_map = {p["id"]: p["name"] for p in catalog}
        lines = []
        for prop in existing:
            prop_name = catalog_map.get(
                prop["definition_id"], f"Property {prop['definition_id']}"
            )
            lines.append(f"- {prop_name}: {prop['value']}")
        return "\n".join(lines) if lines else "(none)"

    @staticmethod
    def _format_existing_relationships(
        existing: list[dict[str, Any]], catalog: list[dict[str, Any]]
    ) -> str:
        """Format existing relationships for prompt."""
        if not existing:
            return "(none)"
        catalog_map = {r["id"]: r["name"] for r in catalog}
        lines = []
        for rel in existing:
            rel_name = catalog_map.get(
                rel["definition_id"], f"Relationship {rel['definition_id']}"
            )
            target = rel.get("target_alias") or rel.get(
                "target_entity_instance_id", "unknown"
            )
            lines.append(f"- {rel_name} -> {target}")
        return "\n".join(lines) if lines else "(none)"

    @staticmethod
    def _format_related_entities(related_entities: list[dict[str, Any]]) -> str:
        """Format allowed relationship targets for prompt grounding."""
        if not related_entities:
            return "[]"
        lines: list[str] = []
        for item in related_entities:
            entity_id = str(item.get("entity_instance_id") or "").strip() or "unknown-id"
            alias = str(item.get("name") or item.get("alias") or "").strip() or "(no alias)"
            entity_type = str(item.get("entity_type_name") or "").strip() or "(unknown type)"
            lines.append(f"- {{name: \"{alias}\", id: \"{entity_id}\", type: \"{entity_type}\"}}")
        return "\n".join(lines)

    @staticmethod
    def _format_scenes_context(scenes: list[dict[str, Any]]) -> str:
        if not scenes:
            return "(none)"
        lines: list[str] = []
        for idx, scene in enumerate(scenes, start=1):
            title = str(scene.get("title") or "Scene").strip()
            description = str(scene.get("description") or "").strip()
            related_items = scene.get("related_entities") or []
            related_parts: list[str] = []
            for item in related_items:
                if isinstance(item, dict):
                    related_parts.append(
                        "{name: \""
                        + str(item.get("name") or "")
                        + "\", id: \""
                        + str(item.get("id") or "")
                        + "\", type: \""
                        + str(item.get("type") or "")
                        + "\"}"
                    )
                else:
                    related_parts.append(str(item))
            related = ", ".join(related_parts)
            lines.append(f"Scene {idx} - Title: {title}")
            lines.append(f"Description: {description or '(no description)'}")
            lines.append(f"Related entities: {related or '(none)'}")
        return "\n".join(lines)

    async def add_relationships_to_entities(
        self,
        *,
        entities: list[OntologyInstanceEntityCreate],
        relationship_data: dict[str, list[dict[str, Any]]],
        entity_alias_map: dict[str, str],
    ) -> list[OntologyInstanceEntityCreate]:
        """Add relationships to entities in a second pass after all entities are created."""
        for entity in entities:
            alias_key = entity.alias.lower().strip()
            if alias_key not in relationship_data:
                continue

            relationships = []
            for rel_data in relationship_data[alias_key]:
                target_alias = rel_data.get("target_alias")
                if not target_alias:
                    continue

                # Check if target exists in new entities or should reference existing
                target_key = target_alias.lower().strip()
                if target_key in entity_alias_map or target_alias:
                    # Target exists, add relationship
                    relationships.append(
                        OntologyInstanceRelationshipCreate(
                            definition_id=rel_data["definition_id"],
                            target_alias=target_alias,
                            data={"justification": rel_data.get("justification", "")},
                        )
                    )

            entity.relationships = relationships

        return entities
