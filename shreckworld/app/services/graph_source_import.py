# These are narrative source *types*, not arbitrary links to world entities.
NARRATIVE_TYPES = (
    (re.compile(r"adventure|campaign|saga|chronicle|book|novel", re.I), 0),
    (re.compile(r"story.?arc|storyline|season|year|volume|part|act", re.I), 1),
    (re.compile(r"session|story|timeline|chapter|episode|entry", re.I), 2),
)
MAX_TREE_NODES = 2000
MAX_TREE_BYTES = 2_000_000


def _id(*parts: object) -> str:
    return str(uuid5(NAMESPACE_URL, "shreckworld-graph-import:" + ":".join(map(str, parts))))


def _rank(type_name: str) -> int | None:
    for expression, rank in NARRATIVE_TYPES:
        if expression.search(type_name):
            return rank
    return None


def _source_text(node: dict) -> tuple[list[dict], str]:
    human = (node.get("text") or "").strip()
    generated = (node.get("autogenerated_text") or "").strip()
    # Linked text is deliberately not imported: it is a rendered derivative.
    paragraphs: list[dict] = []
    if human:
        body = human if not generated or human == generated else "## Authored text\n\n" + human
        paragraphs.append({"id": _id(node["id"], "authored"), "text": body})
    if generated and generated != human:
        body = generated if not human else "## Generated text\n\n" + generated
        paragraphs.append({"id": _id(node["id"], "generated"), "text": body})
    digest = sha256((human + "\0" + generated).encode("utf-8")).hexdigest()
    return paragraphs, digest


@dataclass(frozen=True)
class LegacyType:
    id: int
    name: str


def _legacy_definitions(path: Path) -> tuple[dict[int, LegacyType], dict[int, dict], dict[int, dict]]:
    if not path.is_file():
        raise FileNotFoundError("Legacy ontology database is not mounted")
    # Opens read-only; cannot accidentally migrate or modify the source DB.
    conn = sqlite3.connect(f"file:{path.resolve().as_posix()}?mode=ro", uri=True)
    try:
        conn.row_factory = sqlite3.Row
        types = {int(x["id"]): LegacyType(int(x["id"]), str(x["name"]))
                 for x in conn.execute("SELECT id, name FROM ontology_entities")}
        relationships = {int(x["id"]): dict(x) for x in conn.execute(
            "SELECT id, entity_id, destiny_entity_id, name FROM entity_relationships")}
        props = {int(x["id"]): dict(x) for x in conn.execute(
            "SELECT id, entity_id, name FROM entity_properties")}
        return types, relationships, props
    finally:
        conn.close()


def _graph_pages(settings) -> list[dict]:
    driver = GraphDatabase.driver(
        settings.graph_neo4j_uri,
        auth=(settings.graph_neo4j_user, settings.graph_neo4j_password),
        connection_timeout=5,
    )
    try:
        with driver.session(database=settings.graph_neo4j_database) as graph:
            # The same leaf may anchor many scenes. DISTINCT is essential.
            result = graph.run("""
                MATCH (page:OntologyInstance)-[:HAS_SCENE]->(scene:Scene)
                      -[:DERIVED_FROM]->(leaf:EntityInstance)
                MATCH (page)-[:HAS_ENTITY]->(leaf)
                WHERE toString(scene.instance_id) = toString(page.instance_id)
                RETURN DISTINCT toInteger(page.ontology_id) AS ontology_id,
                       page.instance_id AS instance_id, leaf.entity_instance_id AS leaf_id
                ORDER BY ontology_id, instance_id, leaf_id
            """)
            pages: dict[tuple[int, str], set[str]] = defaultdict(set)
            for record in result:
                if record["ontology_id"] is not None:
                    pages[(int(record["ontology_id"]), str(record["instance_id"]))].add(str(record["leaf_id"]))
            output = []
            for (ontology_id, instance_id), leaves in pages.items():
                entities = {}
                edges = []
                for row in graph.run("""
                    MATCH (page:OntologyInstance {instance_id: $instance_id})
                          -[:HAS_ENTITY]->(entity:EntityInstance)
                    RETURN entity
                """, instance_id=instance_id):
                    obj = dict(row["entity"])
                    identifier = str(obj.get("entity_instance_id") or "")
                    if identifier:
                        entities[identifier] = {
                            "id": identifier,
                            "definition_id": int(obj.get("entity_definition_id") or 0),
                            "title": str(obj.get("alias") or identifier),
                            "text": obj.get("text") or "",
                            "autogenerated_text": obj.get("autogenerated_text") or "",
                            "image": obj.get("node_avatar_url"),
                            "properties": obj.get("properties") or "{}",
                            "created_date": str(obj.get("created_date") or ""),
                        }
                for row in graph.run("""
                    MATCH (page:OntologyInstance {instance_id: $instance_id})
                          -[:HAS_ENTITY]->(a:EntityInstance)
                    MATCH (a)-[r:RELATES_TO]->(b:EntityInstance)<-[:HAS_ENTITY]-(page)
                    RETURN a.entity_instance_id AS a, b.entity_instance_id AS b,
                           r.relationship_definition_id AS definition_id
                """, instance_id=instance_id):
                    if row["a"] and row["b"] and row["definition_id"] is not None:
                        edges.append((str(row["a"]), str(row["b"]), int(row["definition_id"])))
                output.append({"ontology_id": ontology_id, "instance_id": instance_id,
                               "leaves": leaves, "nodes": entities, "edges": edges})
            return output
    finally:
        driver.close()


def _ancestry(leaf_id: str, nodes: dict, edges: list, types: dict, relationship_defs: dict) -> list[str]:
    # Relationship definition IDs are verified rather than following arbitrary graph links.
    neighbours: dict[str, set[str]] = defaultdict(set)
    for source_id, target_id, definition_id in edges:
        definition = relationship_defs.get(definition_id)
        if definition is None or source_id not in nodes or target_id not in nodes:
            continue
        source = nodes[source_id]
        target = nodes[target_id]
        pair = {source["definition_id"], target["definition_id"]}
        if pair != {int(definition["entity_id"]), int(definition["destiny_entity_id"] or -1)}:
            continue
        neighbours[source_id].add(target_id)
        neighbours[target_id].add(source_id)
    result = [leaf_id]
    visited = {leaf_id}
    current = leaf_id
    for _ in range(16):
        node_type = types.get(nodes[current]["definition_id"])
        node_rank = _rank(node_type.name) if node_type else None
        # A scene source with an unknown name is still a leaf candidate.
        current_rank = node_rank if node_rank is not None else 3
        candidates = []
        for neighbour in neighbours[current]:
            if neighbour in visited:
                continue
            target_type = types.get(nodes[neighbour]["definition_id"])
            ancestor_rank = _rank(target_type.name) if target_type else None
            if ancestor_rank is not None and ancestor_rank < current_rank:
                candidates.append((ancestor_rank, neighbour))
        if not candidates:
            break
        best_rank = max(rank for rank, _ in candidates)
        best = sorted(n for rank, n in candidates if rank == best_rank)
        if len(best) != 1:
            raise ValueError("ambiguous ancestor relationship")
        current = best[0]
        result.append(current)
        visited.add(current)
    else:
        raise ValueError("narrative ancestry exceeds 16 levels")
    return list(reversed(result))


def _legacy_image(image_url: object, media_root: Path) -> tuple[bytes, str, str] | None:
    if not isinstance(image_url, str) or not image_url.strip():
        return None
    # Never request arbitrary user-controlled URLs (SSRF); only read known local media.
    path = urlsplit(image_url.strip()).path
    if not path.startswith("/media/"):
        return None
    suffix = unquote(path[len("/media/"):])
    if not suffix or "\0" in suffix:
        return None
    root = media_root.resolve()
    file = (root / suffix).resolve()
    if root not in file.parents or not file.is_file() or file.stat().st_size > 5 * 1024 * 1024:
        return None
    data = file.read_bytes()
    if data.startswith(bytes.fromhex("89504e470d0a1a0a")):
        return data, "png", "image/png"
    if data.startswith(bytes.fromhex("ffd8ff")) and data.endswith(bytes.fromhex("ffd9")):
        return data, "jpg", "image/jpeg"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return data, "webp", "image/webp"
    return None


def _properties(node: dict, prop_defs: dict) -> dict[str, object]:
    try:
        raw = json.loads(node["properties"]) if isinstance(node["properties"], str) else node["properties"]
        return {str(prop_defs[int(k)]["name"]).lower(): value for k, value in raw.items()
                if int(k) in prop_defs} if isinstance(raw, dict) else {}
    except (ValueError, TypeError):
        return {}


def _node_sort(node: dict, prop_defs: dict) -> tuple:
    props = _properties(node, prop_defs)
    for key in ("order", "sequence", "number", "position", "session_number"):
        value = props.get(key)
        if isinstance(value, (int, float)) or (isinstance(value, str) and value.isdigit()):
            return (0, float(value), str(node["title"]).lower(), node["id"])
    return (1, str(node.get("created_date") or ""), str(node["title"]).lower(), node["id"])


def _create_group(db: Session, page: dict, paths: list[list[str]], types: dict,
                  prop_defs: dict, legacy_media_root: Path) -> tuple[int, int]:
    ontology_id, instance_id = page["ontology_id"], page["instance_id"]
    graph_nodes = page["nodes"]
    ids = {id for path in paths for id in path}
    if not ids:
        return 0, 0
    root_id = paths[0][0]
    signature = tuple(types[graph_nodes[n]["definition_id"]].name
                      if graph_nodes[n]["definition_id"] in types else "Story"
                      for n in paths[0])
    source_id = _id(ontology_id, instance_id, root_id, "/".join(signature))
    if db.get(ShreckWorldLibraryItem, source_id):
        return 0, len(ids)
    # Each group has one parent per entity, including the top-level entity.
    parents: dict[str, str | None] = {root_id: None}
    for path in paths:
        for index, identifier in enumerate(path):
            parent = path[index - 1] if index else None
            if identifier in parents and parents[identifier] != parent:
                raise ValueError("narrative node has multiple parents")
            parents[identifier] = parent
    children: dict[str | None, list[str]] = defaultdict(list)
    for identifier, parent in parents.items():
        children[parent].append(identifier)
    template = next((row for row in db.scalars(select(SourceHierarchy).order_by(
        SourceHierarchy.id, SourceHierarchy.version.desc())).all()
        if not row.archived and row.section_types == list(signature)), None)
    if template is None:
        template_id = _id("template", "/".join(signature))
        template = db.get(SourceHierarchy, (template_id, 1))
        if template is None:
            template = SourceHierarchy(id=template_id, version=1,
                name="Imported: " + " → ".join(signature), description="Imported graph narrative path",
                section_types=list(signature), archived=False)
            db.add(template)
    item = ShreckWorldLibraryItem(
        id=source_id, ontology_id=ontology_id, shreckworld_id=None,
        title=graph_nodes[root_id]["title"][:255], source_type="narrative",
        hierarchy_template_id=template.id, hierarchy_template_version=template.version,
        source_revision=1, authored=True, authority_tier="custom", authority_priority=100,
        pdf_path="", source_sha256=sha256(b"").hexdigest(),
        embedding_status="not_embedded", index_status="unindexed", mime_type="text/markdown",
    )
    db.add(item)
    sections: list[SourceSection] = []
    assets: list[SourceAsset] = []
    filepaths: list[Path] = []
    hashes: dict[str, str] = {}
    try:
        def visit(identifier: str, parent_section_id: str | None, order: int) -> None:
            graph = graph_nodes[identifier]
            type_def = types.get(graph["definition_id"])
            kind = type_def.name if type_def else "Story"
            sid = f"source-{source_id}" if parent_section_id is None else _id("section", ontology_id, instance_id, identifier)
            paragraphs, digest = _source_text(graph)
            hashes[identifier] = digest
            props = _properties(graph, prop_defs)
            description = str(props.get("description") or graph["text"] or "")[:10000]
            metadata = SectionMetadata(description=description, summary=description[:10000])
            section = SourceSection(
                id=sid, parent_id=parent_section_id, section_type=kind,
                title=graph["title"][:255], order=order,
                content_reference=AuthoredContent(paragraphs=paragraphs), metadata=metadata)
            if paragraphs:
                identifier_asset = asset_id(source_id, sid, "markdown")
                markdown = markdown_bytes(section)
                path, checksum, created = stage_asset(ontology_id, source_id, identifier_asset, "markdown", markdown, "md")
                if created:
                    filepaths.append(path)
                assets.append(SourceAsset(id=identifier_asset, source_id=source_id, section_id=sid,
                        kind="markdown", storage_path=str(path), mime_type="text/markdown", content_sha256=checksum))
                metadata.markdown_asset_id = identifier_asset
            picture = _legacy_image(graph.get("image"), legacy_media_root)
            if picture:
                data, extension, mime = picture
                identifier_asset = asset_id(source_id, sid, "image")
                path, checksum, created = stage_asset(ontology_id, source_id, identifier_asset, "image", data, extension)
                if created:
                    filepaths.append(path)
                assets.append(SourceAsset(id=identifier_asset, source_id=source_id, section_id=sid,
                        kind="image", storage_path=str(path), mime_type=mime, content_sha256=checksum))
                metadata.image_asset_id = identifier_asset
            sections.append(section)
            for position, child in enumerate(sorted(children.get(identifier, []),
                                  key=lambda key: _node_sort(graph_nodes[key], prop_defs))):
                visit(child, sid, position)
        visit(root_id, None, 0)
        if len(sections) > MAX_TREE_NODES or sum(len(p.text.encode("utf-8"))
                for section in sections for p in section.content_reference.paragraphs) > MAX_TREE_BYTES:
            raise ValueError("Source exceeds organization size limits; split campaign before import")
        rendered = render_authored_markdown(sections)
        original = _write_authored_revision(item, rendered)
        filepaths.append(original)
        item.pdf_path = item.storage_path = str(original)
        item.mime_type = "text/markdown"
        item.source_sha256 = sha256(rendered).hexdigest()
        item.original_filename = re.sub(r"[^a-zA-Z0-9._-]", "-", item.title)[:100] + ".md"
        item.file_size = len(rendered)
        item.description = sections[0].metadata.description
        item.cover_path = next((asset.storage_path for asset in assets
                               if asset.section_id == sections[0].id and asset.kind == "image"), None)
        db.add(SourceOrganization(source_id=source_id, revision=1,
            nodes=[section.model_dump(mode="json") for section in sections]))
        db.add_all(assets)
        for identifier in ids:
            sid = f"source-{source_id}" if identifier == root_id else _id("section", ontology_id, instance_id, identifier)
            db.add(GraphSourceImport(ontology_id=ontology_id, instance_id=instance_id,
                entity_instance_id=identifier, source_id=source_id,
                section_id=sid, source_content_hash=hashes[identifier]))
        db.commit()
        return 1, len(ids)
    except Exception:
        db.rollback()
        for path in filepaths:
            path.unlink(missing_ok=True)
        raise


def import_graph_sources(session_factory, settings=None) -> dict[str, int]:
    """Called after the ShreckWorld database schema is ready.

    Startup import is insert-only: previously imported sources/sections are
    never rewritten, even when legacy text changes after the first import.
    """
    settings = settings or get_settings()
    types, relations, properties = _legacy_definitions(settings.legacy_ontology_database_path)
    pages = _graph_pages(settings)
    summary = dict(pages=len(pages), imported=0, skipped=0, errors=0)
    for page in pages:
        grouped: dict[tuple[str, tuple[str, ...]], list[list[str]]] = defaultdict(list)
        for leaf in page["leaves"]:
            if leaf not in page["nodes"]:
                summary["errors"] += 1
                continue
            try:
                path = _ancestry(leaf, page["nodes"], page["edges"], types, relations)
                signature = tuple(types[page["nodes"][node]["definition_id"]].name
                    if page["nodes"][node]["definition_id"] in types else "Story" for node in path)
                grouped[(path[0], signature)].append(path)
            except ValueError:
                summary["errors"] += 1
                logger.warning("Skipping ambiguous graph narrative source %s", leaf)
        for _, paths in grouped.items():
            try:
                with session_factory() as db:
                    created, skipped = _create_group(
                        db, page, paths, types, properties, settings.legacy_media_root)
                summary["imported"] += created
                summary["skipped"] += skipped
            except Exception as exc:
                summary["errors"] += 1
                logger.warning("Graph narrative group import failed (%s)", type(exc).__name__)
    logger.info("Graph narrative startup import: %s", summary)
    return summary
