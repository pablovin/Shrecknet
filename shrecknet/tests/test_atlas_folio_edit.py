@pytest.mark.asyncio
async def test_patch_preserves_unsupplied_fields_and_scopes_update_to_selected_entity():
    current = page()
    instances = SimpleNamespace(graph_session=None, sql_session=None,
        get_instance=AsyncMock(return_value=current), update_instance=AsyncMock(return_value=current))
    service = AtlasFolioService(instances)
    service.assert_page = AsyncMock()
    result = await service.patch(7, "page", AtlasFolioPatch(expected_updated_at=REVISION, entity_instance_id="one", name="Revised"))
    _, payload = instances.update_instance.call_args.args
    assert payload.name == "Revised"
    assert payload.entities[0].text == "Source"
    assert payload.entities[0].author_id == "4"
    assert payload.entities[0].properties[0].value == ["unchanged"]
    assert instances.update_instance.call_args.kwargs["edit_fields"] == set()
    assert result.folio_projection.relationships == "omitted"
    instances.get_instance.assert_awaited_once_with("page", include_scenes=False, include_relationships=False)


