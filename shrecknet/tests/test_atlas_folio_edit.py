@pytest.mark.asyncio
async def test_partial_update_writes_only_supplied_fields_and_preserves_sibling_facets(monkeypatch):
    import app.services.ontology_instance_service as module
    from app.tasks.neo4j_embedding import embed_nodes
    from app.schemas.ontology_instance import OntologyInstanceEntityCreate, OntologyInstanceUpdate

    current = page()
    sibling = current.entities[0].model_copy(update={"entity_instance_id": "two", "alias": "two"})
    current.entities.append(sibling)
    results = [
        SimpleNamespace(single=AsyncMock(return_value={"revision": REVISION})),
        SimpleNamespace(),
        SimpleNamespace(data=AsyncMock(return_value=[
            {"entity_instance_id": "one", "alias": "one", "definition_id": 1},
            {"entity_instance_id": "two", "alias": "two", "definition_id": 1},
        ])),
        SimpleNamespace(),
    ]
    tx = SimpleNamespace(run=AsyncMock(side_effect=results), commit=AsyncMock(), rollback=AsyncMock(), close=AsyncMock())
    graph = SimpleNamespace(begin_transaction=AsyncMock(return_value=tx), run=AsyncMock())
    service = OntologyInstanceService.__new__(OntologyInstanceService)
    service.graph_session = graph
    service.get_instance = AsyncMock(return_value=current)
    service._load_entity_definitions = AsyncMock(return_value={1: {"properties": {}, "relationships": {}}})
    monkeypatch.setattr(module, "_enqueue_link_instance", lambda _: None)
    monkeypatch.setattr(embed_nodes, "delay", lambda *_: None)
    entity = OntologyInstanceEntityCreate.model_validate(current.entities[0].model_dump())
    entity.text = "Changed text"
    await service.update_instance("page", OntologyInstanceUpdate(entities=[entity]), expected_updated_at=current.updated_at, edit_fields={"text"})
    writes = tx.run.call_args_list[-1].kwargs
    assert writes["entity_instance_id"] == "one"
    assert writes["changes"]["text"] == "Changed text"
    assert writes["changes"]["text_linked"] == "Changed text"
    assert set(writes["changes"]) == {"text", "text_linked", "updated_at", "last_updated_date"}
    assert tx.run.await_count == 4  # No relationship fetch/rewrite.
    tx.commit.assert_awaited_once()
    tx.rollback.assert_not_awaited()
    graph.run.assert_not_awaited()


